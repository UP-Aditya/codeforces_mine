#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        string s;
        cin >> s;
        vector<int> df(n);
        int l= 0,r = n-1;
        for(int i=0;i<n;i++){
            if(s[i]=='L'){
                df[i] = l;
                l++;
            }
            else{
                df[i] = r;
                r--;
            }
        }
        int p = 1;
        vector<int> pp(n);
        for(int i=n-1;i>=0;i--){
            p = (p*v[df[i]])%m;
            pp[i] = p;
        }
        for(auto &i : pp){
            cout << i << " ";
        }
        cout << '\n';

    }
}


