int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t = 1;
    // cin >> t;
    while(t--){
        int n,t;
        cin >> n >> t;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int l=0,r=0,sum=0;
        int df = 0;
        while(r<n){
            sum += v[r];
            while(l<=r && sum > t){
                sum -= v[l];
                l++;
            }
            df = max(df,r-l+1);
            r++;
        }
        cout << df << '\n';
        

    }
}


