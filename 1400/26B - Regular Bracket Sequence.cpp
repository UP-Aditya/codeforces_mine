int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        string s;
        cin >> s;
        stack<char> st;
        int p = 0,c=0;
        for(auto &i : s){
            if(i=='(') st.push('(');
            else if(i==')' && !(st.empty())){
                c += 2;
                st.pop();
            }
            p = max(c,p);
            // if(st.empty()) c=0;
        }
        cout << p;
    }
}


