int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        vector<int> fr(30001,0);
        int n,v;
        cin >> n >> v;
        int a,b;
        int d = 0;
        while(n--){
            cin >> a >> b;
            fr[a] += b;
            d = max(d,a);
        }
        int fc = 0;
        for(int i=1;i<=d+1;i++){
            int cv = v;
            if(fr[i-1]>0){
                int t = min(cv,fr[i-1]);
                cv -= t;
                fc += t;
            }
            if(cv>0 && fr[i]>0){
                int t = min(cv,fr[i]);
                fc += t;
                fr[i] -= t;
                cv -= t;
            }
        }
        cout << fc << '\n';
        
    }
}


