int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        vector<int> a(n);
        vector<int> b(n);
        vector<int> c(n);
        vector<pair<int,int>> p;
        for(int i=0;i<n;i++){
            cin >> a[i];
        }
        for(int i=0;i<m;i++){
            cin >> b[i];
        }
        for(int i=0;i<m;i++){
            cin >> c[i];
        }
        for(int i=0;i<n;i++){
            p[i].first = a[i];
        }
        for(int i=0;i<m;i++){
            p[i].second = c[i];
        }
        sort(p.begin(),p.end());
        sort(b.begin(),b.end());
        if(n>m){
            for(int i=m+1;i<n;i++){
                p[i].second = 0;
            }
        }
        int c = 0;
        for(int i=0;i<min(n,m);i++){
            if(p[i].first > b[i]){
                c++;
            }

        }


    }
}


