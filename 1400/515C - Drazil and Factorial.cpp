int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        string p = "";
        for(int i=0;i<n;i++){
            if(s[i]=='2') p += "2";
            else if(s[i] == '3') p += "3";
            else if(s[i] == '4') p += "322";
            else if(s[i] == '5') p += "5";
            else if(s[i] == '6') p += "53";
            else if(s[i] == '7') p += "7";
            else if(s[i] == '8') p += "7222";
            else if(s[i] == '9') p += "7332";
        }
        sort(p.rbegin(), p.rend());
        cout << p << "\n";
    }
}

