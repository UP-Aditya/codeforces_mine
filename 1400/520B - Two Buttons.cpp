int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        if(m==n) cout << 0 << endl;
        else if(n>m) cout << n-m << endl;
        else{
            int c = 0;
            while(m>n){
                if(m%2){
                    m++;
                    c++;
                }
                m /= 2;
                c++;
            }
            cout << c+abs(n-m) << endl;
        }
    }
}


