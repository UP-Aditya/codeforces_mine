int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        map<int,int> mp;
        int p = 1e6;
        for(int i=0;i<n;i++){
            p = min(p,v[i]);
            if(p!=v[i]){
                mp[v[i]] = p;
            }
        }
        /// I want to check whether I can make the last element largest in the remaining array or not 
        // o r can I remove all elements greater than v[n-1] ?
        for(auto &i : mp){
            cout << i.first << ' ' << i.second << '\n';
        }
        cout << "_______________" << endl;

    }
}


