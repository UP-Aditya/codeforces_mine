#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x;
        cin >> n >> x;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        int c = 0;
        for(int i=n-1;i>=0;){
            if(v[i]>=x) c++;
            else{
                int p = 1e18;
                int df = 0;
                int ct = 0;
                while(i >= 0){
                    ct++;
                    p = min(p,v[i]);
                    df = p*ct;
                    i--;
                    if(df>=x) break;
                }
                if(df>=x){
                    c++;
                    continue;
                }
            }
            i--;
        }
        cout << c << '\n';

    }
}


