int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        if(n==2) cout << "Ashishgup\n";
        else if(n==1 || !(n&(n-1))) cout << "FastestFinger\n";
        else if(n%2) cout << "Ashishgup\n";
        else{
            int c2 = 0,co=0;
            int nn = n;
            for(int i=2;i*i<=nn;i++){
                while(n%i==0 && co<2){
                    if(i%2==0) c2++;
                    if(i%2) co++;
                    n /= i;
                }
                if(co>=2) break;
            }
            if(n>1) co++;
            if(c2>=2 || co>=2) cout << "Ashishgup\n";
            else cout << "FastestFinger\n";
        }
    }
}


