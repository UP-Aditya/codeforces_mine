int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string s;
        cin>>s;
        int n = s.size();
        int c1 = 0,c2=0;
        for(int i=0;i<n;i++){
            if(s[i]=='0') c1++;
            else c2++;
        }
        int df = 1e18;
        for(int i=0;i<n;i++){
            df =min(df,min(c1,c2));
            if(s[i]=='0'){
                c1--;
                c2++;
            }
            else{
                c1++;
                c2--;
            }
        }
        cout << df << endl;

    }
}


