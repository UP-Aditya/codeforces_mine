int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        int a = 1,b = 1;
        for(int i=sqrt(n);i>=1;i--){
            if(n%i==0){
                if(gcd(i,n/i)==1){
                    a = i;
                    b = n/i;
                    break;
                }
            }
        }
        cout << a << " " << b;
    }
}


