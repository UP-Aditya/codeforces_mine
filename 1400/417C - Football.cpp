int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int n,k;
    cin >> n >> k;
    if(n<2*k+1){
        cout << -1;
        return 0;
    }
    vector<pair<int,int>> e;
    for(int i=0;i<n;i++){
        for(int j=1;j<=k;j++){
            int p = (i+j)%n;
            e.push_back({i+1,p+1});
        }
    }
    cout << n*k << endl;
    for(auto &i : e){
        cout << i.first << " " << i.second << "\n";
    }
}

