int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int mx = 0;
        for(int i=0;i<n;i++){
            vector<int> v(n);
            int cp = n;
            for(int j=0;j<i;j++){
                v[j] = j+1;
            }
            for(int j=i;j<n;j++){
                v[j] = cp;
                cp--;
            }
            int cs = 0;
            int mxp = 0;
            for(int j=0;j<n;j++){
                int p = (j+1)*v[j];
                mxp = max(mxp,p);
                cs += p;
            }
            mx = max(mx,cs-mxp);
        }
        cout << mx << '\n';
    }
}

