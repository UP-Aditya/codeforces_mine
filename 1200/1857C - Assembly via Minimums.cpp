int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int x = (n*(n-1))/2;
        vector<int> v(x);
        for(int i=0;i<x;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        vector<int> df;
        int idx = 0;
        int j = n-1;
        while(df.size()!=n-1){
            df.push_back(v[idx]);
            idx += j;
            j--;
        }
        df.push_back(1e9);
        for(auto &i : df){
            cout << i << " ";
        }
        cout << '\n';

    }
}


