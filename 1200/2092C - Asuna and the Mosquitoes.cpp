int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int co = 0,ce = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]%2) co++;
            else ce++;
        }
        int sum = 0;
        if(ce==0 || co==0){
            cout << *max_element(v.begin(),v.end()) << '\n';
        }
        else{
            for(int i=0;i<n;i++){
                if(v[i]%2) sum += v[i]-1;
                else sum += v[i];
            }
            cout << sum+1 << '\n';
        }

        

    }
}


