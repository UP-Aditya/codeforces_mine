int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f = 0;
        for(int i=0;i<n-1;i++){
            if(v[i] != v[i+1]){
                f = 1;
                break;
            }
        }
        if(!f){
            cout << 1 << '\n';
            continue;
        }
        int c = 1;
        int f1 = 0,f2 = 0;
        for(int i=0;i<n-1;i++){
            if(v[i]==v[i+1]) continue;
            else if(v[i]>v[i+1]){
                if(f1){
                    c++;
                    f1 = 0;
                }
                f2 = 1;
            }
            else if(v[i]<v[i+1]){
                if(f2){
                    c++;
                    f2 = 0;
                }
                f1 = 1;
            }
        }
        cout << c+1 << '\n';

    }
}


