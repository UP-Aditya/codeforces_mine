int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x;
        cin >> n >> x;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        int i=0,j=n-1;
        int sum = 0;     
        int df = 0;      
        vector<int> vv;  
        while(i<=j){
            if((sum+v[j])/x > sum/x ){
                sum += v[j];
                df += v[j];
                vv.push_back(v[j]);
                j--;
            }
            else{
                sum += v[i];
                vv.push_back(v[i]);
                i++;
            }
        }
        cout << df << "\n";
        for(auto &i : vv){
            cout << i << " ";
        }
        cout << "\n";
    }
}

