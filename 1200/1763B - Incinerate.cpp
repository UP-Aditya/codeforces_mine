int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        int mx = 0;
        vector<pair<int,int>> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i].second;
            mx = max(mx,v[i].second);
        }
        for(int i=0;i<n;i++){
            cin >> v[i].first;
        }
        if(t==1){
            cout << "NO\n";
            continue;
        }
        sort(v.begin(),v.end());
        for(int i=0;i<n;i++){
            int d = (v[i].second)/k;
            int r = v[i].second%k;
            if(r) d++;
            mx -= d*k - (d-1);
            k -= d-1;
            if(k<=0 || mx<=0) break;
        }
        if(k<=0 || mx <=0) cout << "YES\n";
        else cout << "NO\n";

    }
}


