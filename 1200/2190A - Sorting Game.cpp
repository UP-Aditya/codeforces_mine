int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        string t = s;
        sort(t.begin(),t.end());
        if(s==t){
            cout << "Bob" << '\n';
            continue;
        }    
        cout << "Alice" << '\n';
        vector<int> df;
        for (int i=0;i<n;i++){
            if(s[i] != t[i]){
                df.push_back(i+1);
            }
        }
        cout << df.size() << "\n";
        for(int &i : df){
            cout << i << " ";
        }
        cout << "\n";

    }
}


