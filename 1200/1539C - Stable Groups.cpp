int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,k,x;
        cin >> n >> k >> x;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        vector<int> p;
        for(int i=0;i<n-1;i++){
            if(v[i+1]-v[i]>x){
                p.push_back(v[i+1]-v[i]);
            }
        }
        int d = p.size();
        // for(auto &i : p){
        //     cout << i << " ";
        // }
        // cout << endl;
        sort(p.begin(),p.end());
        for(auto &i : p){
            int df = (i+x-1)/x;
            df--;
            if(df <= k){
                k -= df;
                d--;
            }
            else break;
        }
        cout << d+1;
        

    }
}


