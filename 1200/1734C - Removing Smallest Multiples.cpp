int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int c = 0;
        // map<int,int> mp;
        vector<int> v(n+1,0);
        for(int i=1;i<=n;i++){
            for(int j=i;j<=n;j+=i){
                if(s[j-1]=='1'){
                    break;
                }
                if(!v[j]){
                    c += i;
                    v[j] = 1;
                }
            }
        }
        cout << c << '\n';
    }
}


