int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n+1);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        v[n] = 0;
        int ans = 0;
        for(int i=1;i<n;i+=2){
            if(v[i-1] >= v[i]){
                ans += v[i+1] + v[i-1] - v[i];
                v[i+1] = 0;
                v[i-1] = v[i];
            }
            else if(v[i-1] + v[i+1] > v[i]){
                int x = v[i-1] + v[i+1] - v[i];
                v[i+1] -= x;
                ans += x;
            }
        }
        cout << ans << endl;

    }
}


