int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t; 
    cin >> t;
    while(t--){
        int n,m,q;
        cin >> n >> m >> q;
        vector<int> v(m);
        for(int i=0;i<m;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        while(q--){
            int p;
            cin >> p;
            if(p<v[0]){
                cout << v[0]-1 << "\n";
            }
            else if(p>v[m-1]){
                cout << n-v[m-1] << "\n";
            }
            else{
                auto i = lower_bound(v.begin(),v.end(),p);
                auto j = i;
                j--;
                int l = *j,r = *i;
                int s = (l+r)/2;
                cout << min(s-l,r-s) << "\n";
            }
        }
    }
}



