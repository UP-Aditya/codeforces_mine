#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,a,b;
        cin >> n >> a >> b;
        vector<int> v(n,1);
        int f =-1;
        for(int i=a;i<n;i++){
            v[i]=f;
            f*=-1;
        }
        f=-1;
        b--;
        for(int i=b-1;i>=0;i--){
            v[i]=f;
            f*=-1;
        }
        for(int i=0;i<n;i++){
            cout << v[i] << " ";
            if(i==n-1)
            cout<<'\n';
    }
    
}
}


