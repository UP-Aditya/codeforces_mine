#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,hh;
        cin >> n >> hh;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        auto check = [&](int mid)->bool{
            int x  = 0;
            for(int i=0;i<n-1;i++){
                x += min(v[i+1]-v[i],mid);
                if(x>=hh) return true;
            }
            x += mid;
            return x>=hh;
        };
        int l = 1,h = 1e18;
        int df = -1;
        while(l<=h){
            int mid = l+ (h-l)/2;
            if(check(mid)){
                df = mid;
                h = mid-1;
            }
            else{
                l = mid+1;
            }
        }
        cout << df << '\n';


    }
}


