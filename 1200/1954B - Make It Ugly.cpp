int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        if(*max_element(v.begin(),v.end())==*min_element(v.begin(),v.end())){
            cout << -1 << '\n';
            continue;
        }
        else{
            int c = 0;
            int df = n;
            for(int i=0;i<n;i++){
                if(v[0]==v[i]) c++;
                else{
                    df = min(df,c);
                    c = 0;
                }
            }
            cout << min(df,c) << '\n';
        }

    }
}


