int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m,a,b;
        cin >> n >> m >> a >> b;
        int p,q,r,s;
        p = ceil(log2(double(n)));
        q = ceil(log2(double(min(b,m-b+1))));
        r = ceil(log2(double(m)));
        s = ceil(log2(double(min(a,n-a+1))));
 
        cout<<min(p+q,r+s)+1<<endl;

    }
}


