int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        map<int,int> mp;
        for(int i=0;i<n;i++){
            cin >> v[i];
            mp[v[i]]++;
        }
        int f = 0;
        for(int i=0;i<=n;i++){
            if(mp[i]==0){
                f = 1;
                cout << i << '\n';
                break;
            }
            else if(mp[i]>1){
                mp[i+k]+=mp[i]-1;
                mp[i]=1;
            }
        }
        if(!f){
        cout << n+1 << '\n';
        }

    }
}


