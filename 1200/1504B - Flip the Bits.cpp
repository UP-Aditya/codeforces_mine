int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string a,b;
        cin >> a >> b;
        if(a==b){
            cout << "YES" << '\n';
            continue;
        }
        vector<bool> v(n,false);
        int c0=0,c1=0;
        for(int i=0;i<n;i++){
            if(a[i]=='0') c0++;
            else if(a[i]=='1') c1++;
            if(c0==c1) v[i] = true;
        }
        int f = 0;
        int df = 0;
        for(int i=n-1;i>=0;i--){
            char c = a[i];
            if(f){
                if(a[i]=='0') c = '1';
                else c = '0';
            }
            if(c != b[i]){
                if(!v[i]){
                    cout << "NO\n";
                    df = 1;
                    break; 
                }
                f = !f;
            }
        }
        if(!df)
        cout << "YES\n";

    }
}


