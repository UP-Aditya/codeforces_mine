int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int p = *min_element(v.begin(),v.end());
        if(p==v[0]) cout << "Bob\n";
        else cout << "Alice\n";
    }
}


