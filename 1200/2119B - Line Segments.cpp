#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int px,py,qx,qy;
        cin >> px >> py >> qx >> qy;
        vector<int> v(n);
        int maxx = -1;
        int s = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            maxx = max(v[i],maxx);
            s += v[i];
        }
        int d = (px-qx)*(px-qx) + (py-qy)*(py-qy);
        if(s*s < d){
            cout << "No\n";
            continue;
        }
        int minn = max(0LL,2*maxx-s);
        if(d < minn*minn){
            cout << "No\n";
            continue;
        }
        cout << "Yes\n";
        
    }
}


