int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int x,y;
        cin >> x >> y;
        int k = x/y;
        int df = 1;
        if(x%k==0){
            cout << k << endl;
            continue;
        }
        else{
            for(int i=1;i*i<=x;i++){
                if(x%i==0){
                    if(i<=k) df = max(df,i);
                    if((x/i)<=k) df = max(df,x/i);
                }
            }
        }
        cout << df << endl;

    }
}


