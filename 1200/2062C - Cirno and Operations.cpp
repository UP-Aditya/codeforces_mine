#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> ff;
        int x = accumulate(v.begin(),v.end(),0LL);
        while(n>1){
            for(int i=0;i<n-1;i++){
                ff.push_back(v[i+1]-v[i]);
            }
            x = max(x,abs(accumulate(ff.begin(),ff.end(),0LL)));
            for(int i=0;i<n-1;i++){
                v[i] = ff[i];
            }
            ff.clear();
            n--;
        }
        cout << x << '\n';

    }
}


