#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        for(int i=1;i<=61;i++){
            int x = (1LL << i);
            unordered_set<int> s;
            for(int j=0;j<n;j++){
                s.insert(v[j]%x);
            }
            if(s.size()==2){
                cout << x << '\n';
                break;
            }
        }

    }
}


