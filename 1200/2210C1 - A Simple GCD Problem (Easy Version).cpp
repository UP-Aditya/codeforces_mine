int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int c = 0;
        vector<int> v(n),v1(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        for(int i=0;i<n;i++){
            cin >> v1[i];
        }
        if(n==2){
            if(gcd(v[0],v[1])<v[0]) c++;
            if(gcd(v[0],v[1])<v[1]) c++;
        }
        else{
        if(gcd(v[0],v[1]) < v[0] && v[0]>1){
            c++;
        }
        for(int i=1;i<n-1;i++){
            int p1 = gcd(v[i-1],v[i]);
            int p2 = gcd(v[i],v[i+1]);
            if(((p1*p2)/gcd(p1,p2)) < v[i]) c++;
        }
        if(gcd(v[n-1],v[n-2])<v[n-1]) c++;
    }
    cout << c << '\n';
}
}


