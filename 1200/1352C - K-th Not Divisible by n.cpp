int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        int df = 0;
        int l=1,h=1e18;
        while(l<=h){
            int mid = l + (h-l)/2;
            if(mid%n==0) mid++;
            if(mid - mid/n ==  k){
                df = mid;
                break;
            }
            else if(mid-mid/n > k){
                h = mid-1;
            }
            else{
                l = mid+1;
            }
        }
        cout << df << '\n';

    }
}


