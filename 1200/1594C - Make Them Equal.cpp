int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        char c;
        string s;
        cin >> n >> c >> s;
        vector<int> v;
        int f = 0;
        for(int i=0;i<n;i++){
            if(s[i] != c){
                v.push_back(i+1);
                f = 1;
            }
        }
        if(!f) cout << 0 << '\n';
        else{
            f = -1;
            for(int i=1;i<=n;i++){
                int x = 1;
                for(int j=i;j<=n;j+=i){
                    if(s[j-1] != c){
                        x = 0;
                        break;
                    }
                }
                if(x){
                    f = i;
                    break;
                }
            }
            if(f!=-1){
                cout << 1 << '\n';
                cout << f << '\n';
            }
            else{
                cout << 2 << '\n';
                cout << n << " " << n-1 << '\n';
            }

        }
        

    }
}


