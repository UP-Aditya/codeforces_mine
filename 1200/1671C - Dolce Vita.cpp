int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x;
        cin >> n >> x;
        int s = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
            // s += v[i];
        }
        sort(v.begin(),v.end());
        int c = 0;
        for(int i=0;i<n;i++){
            s += v[i];
            if(s > x) break;  
            c += (x-s)/(i+1);
            c++;
    }
        cout << c << '\n';

    }
}


