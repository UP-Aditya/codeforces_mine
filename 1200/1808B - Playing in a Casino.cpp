int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m;
        cin >> n>> m;
        vector<vector<int>> v(m,vector<int> (n));
        for(int i=0;i<n;i++){
            for(int j=0;j<m;j++){
                cin >> v[j][i];
            }
        }
        int x = 0;
        for(int i=0;i<m;i++){
            sort(v[i].begin(),v[i].end());
            for(int j=0;j<n;j++){
                x += v[i][j]*j;
                x -= v[i][j]*(n-j-1);
            }
        }
        cout << x << endl;

    }
}


