int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        //int fp = 0, fn = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f = 0;
        int cur = v[0];
        for(int i=1;i<n;i++){
            if((v[i]<0 && cur <0) || (cur > 0 && v[i]>0)){
                cur = max(cur,v[i]);
            }
            else{
                f += cur;
                cur = v[i];
            }
        }
        f += cur;
        cout << f << '\n';
    }
}


