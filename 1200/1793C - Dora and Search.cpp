int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        if(n<=3){
            cout << -1 << '\n';
            continue;
        } 
        int mn = 1;
        int mx = n;
        int i=0,j=n-1;
        int f = 0;
        while(i<=j){
            if(v[i]==mn){
                i++;
                mn++;
            }
            else if(v[i]==mx){
                mx--;
                i++;
            }
            else if(v[j]==mx){
                mx--;
                j--;
            }
            else if(v[j]==mn){
                mn++;
                j--;
            }
            else{
                f = 1;
                cout << i+1 << " " << j+1 << '\n';
                break;
            }
        }
        if(!f) cout << -1 << '\n';
    }
}


