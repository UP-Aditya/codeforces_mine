int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        if(n%2==0){
            if(n>=k) cout << k << '\n';
            else{
                if(k%n==0) cout << n << '\n';
                else cout << k%n << '\n';
            }
        }
        else{
            int p = n/2;
            int ht = k/p;
            if(k%p==0) ht--;
            if((ht+k)%n==0) cout << n << '\n';
            else cout << (ht+k)%n << '\n';
            
        }

    }
}


