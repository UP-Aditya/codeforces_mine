int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int p = 0;
        int c = 1;
        for(int i=0;i<n-1;i++){
            if(v[i]==v[i+1]){
                c++;
            }
            else{
                p = max(p,c);
                c = 1;
            }
        }
        p= max(p,c);
        if(p>= m) cout << "NO\n";
        else cout << "YES\n";


    }
}


