#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);


    long long n,k;
    cin>>n>>k;
    while(1){
        if(n==1){
            cout<<1;
            return 0;
        }
        long long x = powl(2,n-1);
        if(k==x){
            cout<<n;
            return 0;
        }
        else if(k<x) n=n-1;
        else{
            k = k-x;
            n-=1;
        }
    }
}


