int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,k,m;
        cin >> n >> k >> m;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        map<int,vector<int>> mp;
        for(auto &i : v){
            mp[i%m].push_back(i);
        }
        int f = 0;
       
            for(auto &i : mp){
                if(i.second.size()>=k){
                    cout << "Yes\n";
                    f = 1;
                    int x = 0;
                    for(auto &j : i.second){
                        cout << j << " ";
                        x++;
                        if(x==k) break;
                    }
                }
                if(f) break;
            }
        if(!f) cout << "No\n";

    }
}


