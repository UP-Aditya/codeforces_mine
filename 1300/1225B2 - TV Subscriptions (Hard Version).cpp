#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k,d;
        cin >> n >> k >> d;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int l=0,r=d-1,df=1e9;
        map<int,int> mp;
        for(int i=0;i<d;i++){
            mp[v[i]]++;
        }
        r++;
        df = min(df,(int)mp.size());
        while(r<n){
            mp[v[r]]++;
            mp[v[l]]--;
            if(mp[v[l]]==0){
                mp.erase(v[l]);
            }
            df = min(df,(int)mp.size());
            l++,r++;
        }
        cout << df << '\n';

    }
}


