int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        int p = 0;
        int mx = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int l = 0;
        unordered_set<int> s;
        for(int i=1;i<n-1;i++){
            if(v[i-1]<v[i] && v[i]>v[i+1]){
                s.insert(i);
                p++;
            }
            if(i-k+1>=0){
                if(s.find(i-k+2)!=s.end()){
                    p--;
                    s.erase(i-k+2);
                }
            }
            if(i-k+2>=0){
                if(mx<p){
                    mx = p;
                    l = i-k+2;
                }
            }
        }
        cout << mx+1 << " " << l+1 << '\n';

    }
}


