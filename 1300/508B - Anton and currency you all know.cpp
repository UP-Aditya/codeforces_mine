int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    string s;
	cin>>s;
	int n=s.length();
    int k=-1;
	for(int i=0;i<n;i++){
		if((s[i]-'0')%2==0){
			k=i;
			if(s[i]<s[n-1]){
				swap(s[i],s[n-1]);
				cout<<s;
				return 0;
			}
		}
	}
	if(k==-1){
		cout<<-1;
		return 0;
	}
	swap(s[k],s[n-1]);
	cout<<s;
}


