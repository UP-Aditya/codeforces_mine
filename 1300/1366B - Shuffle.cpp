int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x,m;
        cin >> n >> x >> m;
        int lf=x,rf=x;
        while(m--){
            int l,r;
            cin >> l >> r;
            if(min(r,rf)>=max(l,lf)){
                rf = max(r,rf);
                lf = min(l,lf);
            }
        }
        cout << rf-lf+1 << '\n';


    }
}


