#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        int b = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            b += __builtin_popcountll(v[i]);
        }

        for(int i=0;i<63;i++){
            for(int j=0;j<n;j++){
                if(!(v[j] & (1LL<<i))){
                    if(k>=(1LL<<i)){
                        k -= (1LL<<i);
                        b++;
                    }
                    else{
                        break;
                    }
                }
            }
            if(k<=0) break;
        }
        cout << b << '\n';


    }
}


