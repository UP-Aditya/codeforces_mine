    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> vv = v;
        sort(vv.begin(),vv.end());
        int c = 0;
        for(int i=0;i<n;i++){
            if(v[i] != vv[i]) c++;
        }
        if(c==2 || c==0) cout << "YES\n";
        else cout << "NO\n";

    }
