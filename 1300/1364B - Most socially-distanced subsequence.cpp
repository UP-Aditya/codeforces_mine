int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> df;
        df.push_back(v[0]);
        int f1 = 0,f2=0;
        for(int i=1;i<n;i++){
            if(v[i-1] > v[i]){
                f2 = 1;
                if(f1)
                df.push_back(v[i-1]);
                f1 = 0;
            }
            else if(v[i-1] < v[i]){
                f1 = 1;
                if(f2)
                df.push_back(v[i-1]);
                f2=0;
            }
        }
        if((!f1 && f2) || (!f2 && f1)) df.push_back(v[n-1]);
        cout << df.size() << '\n';
        for(auto &i : df) cout << i << " ";
        cout << '\n';

    }
}


