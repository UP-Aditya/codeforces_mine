int fact(int p){
    for(int i=2;i*i<=p;i++){
        if(p%i==0){
            return i;
        }
    }
    return -1;
}

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int x = fact(n);
        if(x==-1){
            cout << 1 << " " << n-1 << '\n';
        }
        else if(x==2){
            cout << n/2 << " " << n/2 << '\n';
        }
        else{
            int f = n/x;
            cout << f << " " << n-f << '\n';
        }
    }
}


