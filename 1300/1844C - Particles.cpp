int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int f = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]>0){
                f = 1;
            }
        }
        if(!f){
            int p = (-1)*1e18;
            for(int i=0;i<n;i++){
                p = max(v[i],p);
            }
            cout << p << '\n';
        }
        else{
            int se=0,so=0;
            for(int i=0;i<n;i++){
                if(i&1){
                    if(v[i]>0)
                    se += v[i];
                }
                else{
                    if(v[i]>0)
                    so += v[i];
                }
            }
            cout << max(se,so) << '\n';
        }


    }
}


