int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int g = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            g = gcd(g,v[i]);
        }
        int c = 0;
        for(int i=1;i*i<=g;i++){
            if(g%i==0){  
                c++;
                if(i!=g/i){
                    c++;
                }
            }
        }
        
        cout << c << '\n';



    }
}


