#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int sum = accumulate(v.begin(),v.end(),0LL);
        vector<int> f = v;
        vector<int> ans;
        sort(f.begin(),f.end());
        int p1 = f[n-1];
        int p2 = f[n-2];
        for(int i=0;i<n;i++){
            int x;
            if(v[i]==p1){
                x = p2;
            }
            else x = p1;
            if(sum-v[i]-x == x){
                ans.push_back(i+1);
            }
            
        }
        if(ans.size()==0){
            cout << 0 << '\n';
        }
        else{
        cout << ans.size() << '\n';
        for(auto &i : ans){
            cout << i << " ";
        }
    }
}


