    while(t--){
        int n,m;
        cin >> n >> m;
        int f = 0;
        for(int i=2;i*i<=n;i++){
            if(n%i==0 && i<=m){
                f = 1;
                break;
            }
        }
        if(n<=m && n!=1) f = 1;
        if(f) cout << "NO\n";
        else cout << "YES\n";
        

    }
