    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int mx = 0;
        // int sm = *min_element(v.begin(),v.end());
        vector<int> vv;
        map<int,int> mp;
        for(auto &i : v){
            mp[i]++;
        }
        // mp[sm]--;
        // vv.push_back(sm);
        int f = 0;
        for(auto &i : mp){
            if(i.second>1){
                vv.push_back(i.first);
            }
            else if(i.second==1 && !f){
                vv.push_back(i.first);
                f = 1;
            }
        }
        int x = 0;
        sort(vv.begin(),vv.end());
        for(auto &i : vv){
            if(i==x) x++;
            else break;
        }
        cout << x << '\n';

    }
