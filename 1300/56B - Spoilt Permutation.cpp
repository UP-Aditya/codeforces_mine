int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n+1);
        for(int i=1;i<=n;i++){
            cin >> v[i];
        }
        int l=0,r=0;
        int f1 = 0,f2 = 0;
        for(int i=1;i<=n;i++){
            if(v[i]!=i && !f1){
                f1 = 1;
                l = i;
            }
            if(v[i] != i  && f1){
                r = i;
            }
        }
        int f = 0;
        reverse(v.begin()+l,v.begin()+r+1);
        for(int i=1;i<=n;i++){
            if(v[i]!=i){
                f = 1;
                break;
            }
        }
        if(!f){
            cout << l << " " << r;
        }
        else{
            cout << 0 << " " << 0;
        }

    }
}


