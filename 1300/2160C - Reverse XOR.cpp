int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        for(int i=31;i>=0;i--){
            if(n&(1<<i)) s += '1';
            else s += '0';
        }
        int x = stoll(s);
        string p = to_string(x); 
        int i=0,j=p.size()-1;
        int f = 0;
        while(i<j){
            if(p[i]==p[j]){
                i++,j--;
            }
            else{
                f = 1;
                break;
            }
        }
        if(f) cout << "NO\n";
        else cout << "YES\n";

    }
}


