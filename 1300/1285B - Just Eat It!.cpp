#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int x = accumulate(v.begin(),v.end(),0LL);

        // kadane from 0 to n-2
        // kadane to 1 to n-1

        int cur = 0,df = LLONG_MIN;
        for(int i=0;i<n;i++){
            cur += v[i];
            if(i != n-1) df = max(df,cur);
            if(cur<0) cur = 0;
        }
        cur = 0;
        for(int i=1;i<n;i++){
            cur += v[i];
            df = max(df,cur);
            if(cur<0) cur = 0;
        }
        if(x>df) cout << "YES\n";
        else cout << "NO\n";

    }
}


