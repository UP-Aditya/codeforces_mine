#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int s = accumulate(v.begin(),v.end(),0LL);
        if(s<=k) cout << n << endl;
        else{
            int i=0,j=n-1;
            int c = 0;
            int p = (k+1)/2;
            int q = k/2;
            while(1){
                int f = 0;
                if(p>=v[i]){
                    f = 1;
                    p -= v[i];
                    c++;
                    i++;
                }
                else if(q>=v[j]){
                    f = 1;
                    q -= v[j];
                    c++;
                    j--;
                }
                if(!f) break;
            }
            cout << c << endl;
        }
        

    }
}


