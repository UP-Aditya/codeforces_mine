        int p = s/2;
        for(int i=n;i>=1;i--){
            if(p>=i){
                v.push_back(i);
                p -= i;
            }
        }
        cout << v.size() << " ";
        for(auto &i : v){
            cout << i << " ";
        }
        cout << endl;

