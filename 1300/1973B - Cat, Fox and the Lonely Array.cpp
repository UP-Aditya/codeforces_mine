int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int mxk = 1;
        for(int i=0;i<=20;i++){
            int lp = -1;
            int mx = 0;
            int f = 0;
            for(int j=0;j<n;j++){
                if(((v[j]>>i)&1)){
                    f = 1;
                    mx = max(mx,j-lp);
                    lp = j;
                }
            }
            if(f){
                mx = max(mx,n-lp);
                mxk = max(mxk,mx);
            }
        }
        cout << mxk << '\n';

    }
}


