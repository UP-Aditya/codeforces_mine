int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int p = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i] < v[p]){
                p = i;
            }
        }
        cout << n - 1 << '\n';
        for(int i=0;i<n;i++){
            if(i == p) continue;
            cout << p+1 << " " << i+1 << " " << v[p] << " " << v[p] + abs(i-p) << '\n';
        }
    }
}



