        for(int i=0;i<n-1;i++){
            if(v[i]==v[i+1]){
                c++;
            }
            else{
                if(c>1){
                p += c*(c-1)/2;
                c = 1;
                }
            }
        }
        if(c>1) p+= c*(c-1)/2;   // last group 5 5 4 5 5

        cout << n + p << '\n';
    
