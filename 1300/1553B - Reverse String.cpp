int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string s,t;
        cin >> s >> t;
        int n = s.size(),m = t.size();
        int fg = 0;
        for(int i=0;i<n;i++){
            for(int j=i;j<n;j++){
                int f = 1;
                int ps = i;      
                int pt = 0;      
                while(ps <= j){
                    if(pt == m || s[ps] != t[pt]){
                        f = 0;
                        break;
                    }
                    ps++;
                    pt++;
                }
                if(f==0) continue;
                ps -= 2; 
                while(pt < m){
                    if(ps <0 || s[ps] != t[pt]){
                        f = 0;
                        break;
                    }
                    ps--;
                    pt++;
                }
                if(f){
                    fg = 1;
                    break;
                }
            }
            if(fg) break;
        }
        if(fg) cout << "YES\n";
        else cout << "NO\n";
    }
}


