int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int cnt;
        int c = 0;
        auto check = [&](int mid)->bool{
            cnt = 0,c=0;
            vector<int> vp;
            for(int i=0;i<n;i++){
                vp.push_back((i+1)*mid+v[i]);
            }
            sort(vp.begin(),vp.end());
            for(int i=0;i<mid;i++){
                c += vp[i];
                cnt++;
            }
            // for(auto &i : vp){
            //     cout << i.first << " " << i.second << '\n';
            // }
            // cout << "--------" << endl;
            if(c<=k) return true;
            return false;
        };
        int l=0,h=n;
        int df = -1;
        int pp = 0;
        while(l<=h){
            int mid = l + (h-l)/2;
            if(check(mid)){
                df = mid;
                pp =c;
                l = mid+1;
            }
            else h = mid-1;
        }
        cout << df << " " << pp << '\n';

    }
}


