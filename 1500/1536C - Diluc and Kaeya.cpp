#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int cd=0,ck=0;
        map<pair<int,int>,int> mp;
        for(int i=0;i<n;i++){
            if(s[i]=='D') cd++;
            else ck++;
            int g = gcd(cd,ck);
            mp[{cd/g,ck/g}]++;
            cout << mp[{cd/g,ck/g}] << " ";
        }
        cout << '\n';

    }
}


