int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        vector<int> df;
        int i=0,j=n/2;
        while(j<n){
            df.push_back(v[j]);
            if(i==n/2) break;
            df.push_back(v[i]);
            j++,i++;
        }
        int c = 0;
        for(int i=1;i<n-1;i++){
            if(df[i-1]>df[i] && df[i]<df[i+1]) c++;
        }
        cout << c << '\n';
        for(auto &i : df) cout << i << " ";

    }
}


