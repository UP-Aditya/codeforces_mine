int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> df;
        for(int i=2;i<=n;i++){
            int f = 0;
            for(int j=2;j*j<=i;j++){
                if(i%j==0){
                    f = 1;
                    break;
                }
            }
            if(!f){
                int p = i;
                df.push_back(p);
                while(p<=n){
                    p *= i;
                    if(p<=n)
                    df.push_back(p);
                }
            }
        }
        cout << df.size() << '\n';
        for(auto &i : df) cout << i << " ";


    }
}


