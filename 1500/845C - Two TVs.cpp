int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<pair<int,int>> vp;
        int x,y;
        for(int i=0;i<n;i++){
            cin >> x >> y;
            vp.push_back({x,y});
        }
        sort(vp.begin(),vp.end());
        int f = 1;
        int l = -1;
        int r = -1;
        for(int i=0;i<n;i++){
            if(vp[i].first > l){
                l = vp[i].second;
            }
            else if(vp[i].first > r){
                r = vp[i].second;
            }
            else{
                f = 0;
            }
        }
        if(f) cout << "YES\n";
        else cout << "NO\n";

    }
}


