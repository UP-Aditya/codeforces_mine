bool check(vector<int> &a,vector<int> &b,int k,int mid){
    int r = 0;
    for(int i=0;i<a.size();i++){
        if(b[i]/a[i]<mid){
            int n = mid-(b[i]/a[i]);
            r += n*a[i] - (b[i]%a[i]);
        }
        if(r>k) return false;
    }
    if(r<=k) return true;
    else return false;
}
int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> a(n),b(n);
        for(int i=0;i<n;i++){
            cin >> a[i];
        }
        for(int i=0;i<n;i++){
            cin >> b[i];
        }
        int l = 0,h = 1e10;
        int df = 0;
        while(l<=h){
            int mid = l + (h-l)/2;
            if(check(a,b,k,mid)){
                l = mid+1;
                df = mid;
            }
            else{
                h = mid-1;
            }
        }
        cout << df << '\n';


    }
}


