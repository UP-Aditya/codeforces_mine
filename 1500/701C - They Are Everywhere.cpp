int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        set<char> st(s.begin(),s.end());
        int k = st.size();
        int df=1e9,l=0,r=0;
        map<char,int> mp;
        while(r<n){
            mp[s[r]]++;
            while(mp.size()==k){
                df = min(df,r-l+1);
                mp[s[l]]--;
                if(mp[s[l]]==0){
                    mp.erase(s[l]);
                }
                l++;
            }
            r++;
        }
        cout << df;

    }
}


