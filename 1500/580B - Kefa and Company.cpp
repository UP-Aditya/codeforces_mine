int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,d;
        cin >> n >> d;
        vector<pair<int,int>> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i].first >> v[i].second;
        }
        sort(v.begin(),v.end());
        int sum=0,l=0,r=0;
        int df = 0;
        while(r<n){
            sum += v[r].second;
            while(v[r].first-v[l].first >= d){
                sum -= v[l].second;
                l++;
            }
            df = max(df,sum);
            r++;
        }
        cout << df << '\n';

    }


}


