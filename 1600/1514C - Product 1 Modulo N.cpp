#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        int p = 1;
        vector<int> df;
        for(int i=1;i<n;i++){
            if(gcd(i,n)==1){
                df.push_back(i); 
                p = (p*i)%n;
            }
        }
        if(p==1){
            cout << df.size() << '\n';
            for(auto &i : df){
                cout << i << " ";
            }
        }
        else{
            cout << df.size()-1 << '\n';
            for(auto &i : df){
                if(i==p) continue;
                cout << i << " ";
            }
        }

    }
}


