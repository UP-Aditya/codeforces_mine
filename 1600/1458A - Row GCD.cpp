int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> a(m);
        for(int i=0;i<m;i++) cin >> a[i];
        int g = 0;
        for(int i=1;i<n;i++){
            int d = v[i]-v[i-1];
            g = gcd(g,d);
        }
        for(int i=0;i<m;i++){
            cout <<  gcd(v[0]+a[i],g) << " ";
        }

    }
}


