int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int a,b;
        cin >> a >> b;
        int c = 0;
        while(a>0 && b>0){
            if(a>b){
                c += a/b;
                a %= b;
            }
            else{
                c += b/a;
                b%= a;
            }
        }
        cout << c << '\n';
    }
}


