#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int s=  accumulate(v.begin(),v.end(),0LL);
        int op =0;
        int mn = *min_element(v.begin(),v.end());
        sort(v.begin(),v.end());
        for(auto &i : v){
            cout <<i << " ";
        }
        cout << endl;
        
        for(int i=n-1;i>=0;i--){
            if(s<=k) break;
            if(v[i]>mn){
                s -= v[i];
                s += mn;
                op++;
            }
        }
        if(s<=k){
            cout << op << '\n';
        }
        else{
            cout << op + (s-k) << '\n';
        }


    }
}


