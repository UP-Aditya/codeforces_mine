int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b,x;
        cin >> a >> b >> x;
        int d = abs(a-b);
        int c=0;
        vector<int> df;
        if(a==b){
            cout << 0 << '\n';
            continue;
        }
        while(a!=b){
            if(a==b) break;
            if(a>b) a /= x;
            else b /= x;
            c++;
            df.push_back(c+abs(a-b));
        }
        int p = *min_element(df.begin(),df.end());
        cout << min(p,d) << '\n';
    }
}


