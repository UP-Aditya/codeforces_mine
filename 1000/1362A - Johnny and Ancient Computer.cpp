int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b;
        cin >> a >> b;
        int x = a,y = b;
        int a2 =0, b2 = 0;
        while(x%2==0){
            x /= 2;
            a2++;
        }
        while(y%2==0){
            y /= 2;
            b2++;
        }
        if(x!=y) cout << -1 << '\n';
        else{
            cout << ceil(abs(a2-b2)/3.0)<< '\n';
        }
        


    }
}


