int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f = 1;
        for(int i=0;i<n;i++){
            for(int j=i+1;j<n;j++){
                if(v[i]==v[j]){
                    f = 0;
                    break;
                }
            }
        }
        if(f) cout << "NO\n";
        else cout << "YES\n";

    }
}


