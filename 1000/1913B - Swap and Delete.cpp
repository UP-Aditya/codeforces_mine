int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string s;
        cin >> s;
        int c1=0,c0=0;
        for(int i=0;i<s.size();i++){
            if(s[i]=='0') c0++;
            else c1++;
        }
        int p = 0;
        for(int i=0;i<s.size();i++){
            if(s[i]=='0'){
                if(c1==0) break;
                c1--;
                p++;
            }
            else{
                if(c0==0) break;
                c0--;
                p++;
            }
          //  if(c0==0 || c1==0) break;
        }
        cout << s.size() - p << '\n';
        
    }
}


