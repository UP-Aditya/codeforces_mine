int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin>>s;
        map<string,int> mp;
        int f  = 0;
        for(int i=0;i<n-1;i++){
            string p = "";
            p += s[i];
            p += s[i+1];
            if(mp.find(p)!=mp.end()){
                if(mp[p]<=i-2){
                    cout<<"YES\n";
                    f = 1;
                    break;
                }
            }
            else{
                mp[p]=i;
            }
        }
        if(!f)
        cout<<"NO\n";

    }
}


