int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int m; 
        cin >> m;
        while(m--){
            string s; 
            cin >> s;
            if(s.size()!=n){
                cout << "NO\n";
                continue;
            }
            map<char,int> mp1;
            map<int,char> mp2;
            bool ok=1;
            for(int i=0;i<n;i++){
                char ch = s[i];
                int num = v[i];
                if(mp1.count(ch) && mp1[ch]!=num) ok = 0;
                if(mp2.count(num) && mp2[num]!=ch) ok = 0;
                mp1[ch] = num;
                mp2[num] = ch;
            }
            if(ok) cout << "YES\n";
            else cout << "NO\n";
        }

    }
}


