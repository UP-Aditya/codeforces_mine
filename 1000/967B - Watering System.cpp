int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

        int n,A,B;
        cin >> n >> A >> B;
        int fh;
        cin >> fh;
        int s = fh;
        vector<int> v(n-1);
        for(int i=0;i<n-1;i++){
            cin >> v[i];
            s += v[i];
        }
        sort(v.rbegin(),v.rend());
        //reverse(v.begin(),v.end());
        if((fh*A)/s >=B) cout << 0 << '\n';
        else{
            int c = 0;
            for(int i=0;i<n-1;i++){
                s -= v[i];
                c++;
                if((fh*A)/s >= B) break;
            }
            cout << c << '\n';
        }
        

}


