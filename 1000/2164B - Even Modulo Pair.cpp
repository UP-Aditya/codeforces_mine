int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f = 0;
        if(n<=100){
            for(int i=0;i<n;i++){
                for(int j=i+1;j<n;j++){
                    int x = v[j]%v[i];
                    if(!(x&1)){
                        cout << v[i] << " " << v[j];
                        f = 1;
                        break;
                    }
                }
                if(f) break;
            }
        }
        else{
            for(int i=0;i<100;i++){
                for(int j=i+1;j<n;j++){
                    int x = v[j]%v[i];
                    if(!(x%2)){
                        cout << v[i] << " " << v[j];
                        f = 1;
                        break;
                    }
                }
                if(f) break;
            }
            
        }
        if(!f) cout << -1;
        cout << '\n';


    }
}


