int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int p;
        cin >> p;
        int s = 0;
        vector<int> sec_min;
        vector<int> f_min;
        while(p--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        sec_min.push_back(v[1]);
        f_min.push_back(v[0]);
    }
    sort(sec_min.begin(),sec_min.end());
    sort(f_min.begin(),f_min.end());
    for(int i=0;i<sec_min.size();i++){
        s += sec_min[i];
    }
    s -= sec_min[0];
    cout << s + f_min[0] << '\n';

}
}


