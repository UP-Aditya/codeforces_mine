int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        int df = 0;
        for(int i=0;i<=n;i++){
            if((i==0 || v[i-1]<i) && (i==n || v[i]>i)){
                df++;
            }
        }
        cout << df << "\n";
    }
}


