#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--) {
        int n, k;
        cin >> n >> k;
        string s;
        cin >> s;
        vector<int> bg(26,0),sm(26,0);
        for(char c:s){
            if(isupper(c)){
                bg[c-'A']++;
            } 
            else{
                sm[c-'a']++;
            }
        }
        int f = 0;

        for(int i=0;i<26;i++){
            int comm = min(bg[i],sm[i]);
            f += comm;
            bg[i] -= comm;
            sm[i] -= comm;
        }
        for(int i=0;i<26;i++){
            int lf = max(bg[i],sm[i])/2;
            int ad = min(lf,k);
            f += ad;
            k -= ad;
        }
        cout << f << '\n';
    }
}


