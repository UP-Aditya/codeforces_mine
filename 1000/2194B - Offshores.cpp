int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x,y;
        cin >> n >> x >> y;
        vector<int> v(n);
        int p = -1;
        int m = -1e18;
        for(int i=0;i<n;i++){
            cin >> v[i];
            int df = v[i]-(v[i]/x)*y;
            if(df > m){
                p = v[i];
                m = df;
            }
        }
        int c = 0;
        int f = 0;
        for(int i=0;i<n;i++){
            if(v[i]==p && !f){
                f = 1;
                continue;
            }
            else{
                c += (v[i]/x)*y;
            }
        }
        cout << c+p << endl;

    }
}


