int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        vector<int> v1,v2;
        for(int i=0;i<n;i++){
            if(s[i]=='1'){
                v1.push_back(i+1);
            } 
            else{
                v2.push_back(i+1);
            }
        }
        if(v1.size()%2==0){
            cout << v1.size() << "\n";
            for(auto &i : v1) cout << i << " ";
            cout << "\n";
        } 
        else if(v2.size()%2!=0){
            cout << v2.size() << "\n";
            for(auto &i : v2) cout << i << " ";
            cout << "\n";
        } 
        else{
            cout << -1 << "\n";
        }
    }
}


