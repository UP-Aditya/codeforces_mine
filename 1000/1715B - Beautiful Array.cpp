int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k,b,s;
        cin >> n >> k >> b >> s;
        int mns = k*b;
        int mxs = k*b+(k-1)*n;
        if(s<mns || s>mxs) cout << -1 << '\n';
        else{
            vector<int> v(n,0);
            v[0] = mns;
            s -= mns;
            for(int i=0;i<n;i++){
                int p  = min(k-1,s);
                v[i] += p;
                s -= p;
            }
            for(int i=0;i<n;i++){
                cout << v[i] << " ";
            }
            cout << '\n';
        }

    }
}


