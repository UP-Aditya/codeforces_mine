int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        map<int,int> mp;
        int f1=0,f2=0,f3=0;
        for(int i=0;i<n;i++){
            mp[v[i]]++;
            if(!f1 && mp[1]>=(mp[2]+mp[3])){
                int g=0;
                f1=1;
                while(i+1<n && mp[1]>(mp[2]+mp[3]) && v[i+1]==3){
                    mp[1]--;
                    g=1;
                    i++;
                }
                mp[1]=0;
                mp[2]=0;
                mp[3]=0;
            }
            else if(f1 && !f2 && (mp[1]+mp[2])>=mp[3]){
                f2=1;
                if(i<n-1){
                    f3=1;
                    break;
                }
            }
        }
        if(f1 && f2 && f3) cout << "YES\n";
        else cout << "NO\n";

    }
}


