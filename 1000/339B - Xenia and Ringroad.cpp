int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int n,m;
    cin >> n >> m;
    int time = 0;
    int s = 1;
    vector<int> v(m);
    for(int i=0;i<m;i++){
        cin >> v[i];
    }
    for(int i=0;i<m;i++){
        if(v[i]>=s){
            time += v[i]-s;
        } 
        else{
            time += n-s+v[i];
        }
        s = v[i];
    }
    cout << time;
    
}


