int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int c = 0;
        for(int i=0;i<n;i++){
            if(s[i] == '1'){
                c++;
            }
        }
        cout << c << '\n';
        for(int i=0;i<n;i++){
            if(s[i] == '1'){
                cout << i+1 << " ";
            }
        }
        cout << '\n';
    }
}


