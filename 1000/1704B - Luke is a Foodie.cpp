int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x;
        cin >> n >> x;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int l = v[0] - x;
        int r = v[0] + x;
        int c = 0;
        for(int i=1;i<n;i++){
            int nl = v[i] - x;
            int nr = v[i] + x;
            l = max(nl,l);
            r = min(nr,r);
            if(l>r){
                c++;
                l = nl;
                r = nr;
            }
        }
        cout << c << '\n';
    }
}


