int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        vector<int> p(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        for(int i=0;i<n;i++){
            cin >> p[i];
        }
        int idx = -1;
        for(int i=0;i<n;i++){
            if(v[i] < p[i]){
                if(idx != -1){
                    idx = -2;
                    break;
                }
                idx = i;
            }
        }

        if(idx == -1){
            cout << "YES\n";
            continue;
        }
        if(idx == -2){
            cout << "NO\n";
            continue;
        }
        int x = p[idx]-v[idx];
        int ok = 1;
        for(int j=0;j<n;j++){
            if(j == idx) continue;
            if(v[j] - p[j] < x){
                ok = 0;
                break;
            }
        }

        if(ok) cout << "YES\n";
        else cout << "NO\n";
    }
    }



