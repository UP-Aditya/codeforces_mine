int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int c = 4;
        if(n==1) cout << 1 << '\n';
        else if(n==2) cout << 1 << " " << 2 << '\n';
        else{
        vector<int> v(n,0);
        v[0] = 2;
        v[n/2] = 1;
        v[n-1] = 3;
        for(int i=0;i<n;i++){
            if(v[i] == 0){
                v[i] = c;
                c++;
            }
        }
        for(int i=0;i<n;i++){
            cout << v[i] << " ";
        }
        cout << '\n';
    }
    }
}


