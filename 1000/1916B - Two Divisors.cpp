int32_t main()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while (t--)
    {
        int a, b;
        cin >> a >> b;

        if (a == 1)
        {
            cout << b * b << '\n';
        }
        else
        {
            if (b % a == 0)
                cout << b * b / a << '\n';
            else
                cout << a * b / gcd(a, b) << '\n';
        }
    }
}

