int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> pmax(n+1,0);
        vector<int> psum(n+1,0);
        
        for(int i=0;i<n;i++){
            pmax[i+1] = max(pmax[i],v[i]);
            psum[i+1] = psum[i]+v[i];
        }
        for(int i=1;i<=n;i++){
            cout << pmax[n-i+ 1] + psum[n] - psum[n-i+1] << " ";
        }
        cout << "\n";
    }
}


