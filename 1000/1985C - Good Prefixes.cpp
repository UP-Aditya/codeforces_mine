int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int s = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f = 0;
        int mx = 0;
        for(int i=0;i<n;i++){
            s += v[i];
            mx = max(mx,v[i]);
            if(s-mx == mx) f++;
        }
        cout << f << '\n';
    }
}


