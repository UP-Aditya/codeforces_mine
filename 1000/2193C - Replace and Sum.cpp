int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,q;
        cin >> n >> q;
        vector<int> a(n),b(n);
        for(int i=0;i<n;i++){
            cin >> a[i];
        }
        for(int i=0;i<n;i++){
            cin >> b[i];
        }
        vector<int> v(n,0);
        int mx = 0;
        for(int i=n-1;i>=0;i--){
            mx = max({mx,a[i],b[i]});
            a[i] = mx;
        }
        // v[n-1] = max(b[n-1],a[n-1]);
        vector<int> pre(n+1,0);
        pre[0] = a[0];
        for(int i=1;i<=n;i++){
            pre[i] = pre[i-1] + a[i-1];
        }
        while(q--){
            int l,r;
            cin >> l >> r;
            cout << pre[r] - pre[l-1] << " ";
        }
        cout << endl;

    }
}


