bool ff(int n){
    int x = n;
    while(x){
        int d = x%10;
        if(d!=0 && n%d!=0) 
        return false;
        x /= 10;
    }
    return true;
}

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        while(1){
            if(ff(n)) break;
            n++;
        }
        cout << n << '\n';
    }
}

