int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int sum = 0;
        int op = 0;
        for(int i=0;i<n;i++){
            if(s[i]=='('){
                sum++;
            }
            else if(s[i]==')'){
                sum--;
            }
            if(sum<0){
                op++;
                sum = 0;
            }
        }
        cout << op << '\n';

    }
}


