int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        vector<int> ans(n,0);
        for(int i=0;i<n;i++) cin >> v[i];
        int mn = INT_MAX;
        int mx = INT_MIN;
        for(int i=0;i<n;i++){
            if(v[i]<mn){
                mn = v[i];
                ans[i] = 1;
            }
        }
        for(int i=n-1;i>=0;i--){
            if(v[i]>mx){
                mx = v[i];
                ans[i] = 1;
            }
        }
        for(auto &i : ans) cout << i;
        cout << '\n';

    }
}


