int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int c1 = 1;
        int c2 = 1;
        if(n<3){
            if(n==1) cout << 0 << '\n';
            else if(n==2 && v[0]==v[1]) cout << 0 << '\n';
            else cout << 1 << '\n';
        }
        else{
            int x = v[0];
            int y = v[n-1];
            for(int i=1;i<n;i++){
                if(v[i]==x) c1++;
                else break;
            }
            for(int i=n-2;i>=0;i--){
                if(v[i]==y) c2++;
                else break;
            }
            if(c1==n || c2==n) cout << 0 << '\n';
            else if(x==y) cout << n-(c1+c2) << '\n';
            else cout << n-max(c1,c2) << '\n';
        }

    }
}


