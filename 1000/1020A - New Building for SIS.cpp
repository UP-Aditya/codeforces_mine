int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

        int n,h,a,b,k;
        cin >> n >> h >> a >> b >> k;
        while(k--){
            int ta,fa,tb,fb;
            cin >> ta >> fa >> tb >> fb;
            if(ta==tb){
                cout << abs(fa-fb) << '\n';
            }
            else if(a<=fa && b>=fa){
                cout << abs(fa-fb)+abs(ta-tb) << '\n';
            }
            else{
                int p;
                if(abs(a-fa)>abs(b-fa)){
                    p = b;
                }
                else p = a;

                cout << abs(ta-tb) + abs(p-fb) + abs(p-fa) << '\n';
            }
        }

    
}


