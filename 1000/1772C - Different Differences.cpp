int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int k,n;
        cin>>k>>n;
        deque<int>dq;
        int i=n;
        while(dq.size()<k&&dq.front()-1>k-dq.size()){
            dq.push_front(i);
            if(dq.front()-1<=k)break;
            i-=dq.size();
        }
        vector<int>ans;
        int x=1;
        while(dq.size()+ans.size()<k){
            ans.push_back(x++);
        }
        for(auto&v:ans)
        cout<<v<<" ";
        for(auto&v:dq)
        cout<<v<<" ";
        cout<<"\n";
    }
    return 0;
}

