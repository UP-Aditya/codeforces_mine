int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int w,h;
        cin >> w >> h;
        int p = 0;

        for(int i=0;i<4;i++){
            int k;
            cin >> k;
            vector<int> v(k);
            for(int j=0;j<k;j++) cin >> v[j];
            int l = v[k-1]-v[0];
            int hh;
            if(i<2) hh = h;
            else hh = w;
            p = max(p,l*hh);
        }
        cout << p << '\n';
    }

}



