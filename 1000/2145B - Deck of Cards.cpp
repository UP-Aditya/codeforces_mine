int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        string s;
        cin >> s;
        string p = "";
        if(n==k){
            while(n--){
                p += '-';
            }
            cout << p << '\n';
            continue;
        }
        else{
            int c1=0,c0=0,c2=0;
            for(auto &i : s){
                if(i=='0') c0++;
                else if(i=='1') c1++;
                else c2++;
            }
            while(n--){
                p += '+';
            }
            for(int i=0;i<c0;i++){
                p[i] = '-';
            }
            int x = c1;
            int j = p.size()-1;
            while(x--){
                p[j] = '-';
                j--;
            }
            if(c2){
                while(c2--){
                    p[c0] = '?';
                    p[p.size()-c1-1] = '?';
                    c0++;
                    c1++;
                }
            }
            cout << p << '\n';

        }
        
    }
}


