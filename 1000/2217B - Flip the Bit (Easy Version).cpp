int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int f;
        cin >> f;
        f--;
        int c1=0,c2=0;
        for(int i=0;i<f;i++){
            if(v[i]!=v[i+1]) c1++;
        }
        for(int i=f;i<n-1;i++){
            if(v[i]!=v[i+1]) c2++;
        }
        if(max(c1,c2)%2) cout << max(c1,c2)+1 << '\n';
        else cout << max(c1,c2) << '\n';
    }
}


