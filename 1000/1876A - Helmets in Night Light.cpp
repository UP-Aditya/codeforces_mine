int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> a(n);
        vector<int> b(n);

        for(int i=0;i<n;i++){
            cin >> a[i];
        }
        for(int i=0;i<n;i++){
            cin >> b[i];
        }
        vector<pair<int,int>> p(n);
        for(int i=0;i<n;i++){
            p[i].first = b[i];
            p[i].second = a[i];        
        }

        sort(p.begin(),p.end());
        int req = n-1;
        int c = k;
        for(int i=0;i<n;i++){
            int share_count = p[i].second;
            int share_cost = p[i].first;

            if(share_cost >= k)
                break;
            int use = min(req,share_count);
            c += use * share_cost;
            req -= use;
            if(req == 0)
                break;
        }
        if(req>0)
            c += req * k;

        cout << c << '\n';
        }
    }



