int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        n--;
        int p = log2(n);
        vector<int> v;
        int n1 = pow(2,p)-1;

        while(n1>=0){
            v.push_back(n1);
            n1--;
        }
        n1 = pow(2,p);
        while(n1<=n){
            v.push_back(n1);
            n1++;
        }
        for(auto &i : v){
            cout << i << " ";
        }
        cout << '\n';
    }
}

