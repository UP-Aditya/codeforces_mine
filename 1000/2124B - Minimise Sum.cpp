int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int c1=0,c2=0,c3=0;
        if(v[1]==0) cout << v[0] << '\n';
        else{
        c1 = v[0]*n;
        c2 = v[0]+v[1];
        c3 = v[0]*2;
        int p = min(c1,c2);
        cout << min(p,c3) << '\n';
        }
    }
}


