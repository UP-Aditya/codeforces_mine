#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    int t;
    cin >> t;
    while(t--){
        string a,b;
        cin >> a >> b;
        long long n = a.size(),m = b.size();
        long long lcs = 0;
        for(long long l=1;l<=min(n,m);l++){
            for(long long i=0;i<=n-l;i++){
                for(long long j=0;j<=m-l;j++){
                    string ea = a.substr(i,l);
                    string eb = b.substr(j,l);
                    if(ea==eb){
                        lcs = max(lcs,l);
                    }
                }
            }
        }
        long long op = n+m-2*lcs;
        cout << op << endl;
    }
}
    



