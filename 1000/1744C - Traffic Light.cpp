int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        char ch;
        cin >> ch;
        string s;
        cin >> s;
        if(ch=='g'){
            cout << 0 << '\n';
        }
        else{
        string p = s + s;
        vector<int> v;
        for(int i=0;i<n*2;i++){
            if(p[i]=='g'){
                v.push_back(i);
            }
        }
        int mx = 0;
        for(int i=0;i<n*2;i++){
            if(p[i]==ch){
                for(int j=0;j<v.size();j++){
                    if(v[j]>i){
                        mx = max(mx,v[j]-i);
                        break;
                    }
                }
            }
        }
        cout << mx << '\n';


    }
    }
}


