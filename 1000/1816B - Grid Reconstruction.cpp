int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<vector<int>> v(2,vector<int> (n));
        v[0][0] = 2*n;
        int i=2;
        int j = 2*n-2;
        int x = 1;
        while(i<=j){
            v[0][x++] = i;
            i += 2;
            if(i==j) break;
            v[0][x++] = j;
            j -= 2;
        }
        i = 1,j=2*n-3;
        x=0;
        while(i<=j){
            v[1][x++] = i;
            i += 2;
            if(i==j) break;
            v[1][x++] = j;
            j -= 2;
        }
        v[1][n-1] = 2*n-1;
        for(auto &i : v){
            for(auto &j : i){
                cout << j << " ";
            }
            cout << '\n';
        }

    }
}


