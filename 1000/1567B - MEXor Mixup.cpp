#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62
long long xt(int n){
    if(n%4==0) return n;
    if(n%4==1) return 1;
    if(n%4==2) return n+1;
    return 0;
}
int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    int t;
    cin >> t;
    while(t--){
        int a,b;
        cin >> a >> b;
        int ax = xt(a-1);
        if(ax==b)
            cout << a << endl;
        else if((ax^b)!=a)
            cout << a+1 << '\n';
        else
            cout << a+2 << '\n';
    }
}

