int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin>>n;
        int p=1;
        int i=0;
        int ans=0;
        while(n>0){
            int m=n%3;  
            n/=3;
            if(m>0){
                int c=p*3;
                if(i>0) c+=i*(p/3);
                ans+=m*c;
            }
            p*=3;
            i++;
        }
        cout<<ans<<endl;
    }
}


