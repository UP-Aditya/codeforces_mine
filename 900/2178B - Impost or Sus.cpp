int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string r;
        cin >> r;
        int n = r.size();
        int df = 0;
        if(r[0]=='u'){
            r[0] = 's';
            df++;
        }
        if(r[n-1]=='u'){
            r[n-1] = 's';
            df++;
        }
        int uc = 0;
        for(int i=1;i<n-1;i++){
            if (r[i]=='u'){
                uc++;
            } 
            else{
                df += uc/2;
                uc = 0;
            }
        }
        df += uc/2;
        cout << df << "\n";
    }
}


