int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> vv = v;
        sort(vv.begin(),vv.end());
        int c = 2;
        int f = 0;
        for(int i=n-1;i>=n/2 && c>0;i--){
            if((i+1)%2){
                if(vv[i]!=v[i]){
                    f = 1;
                    break;
                }
                c--;
            }
        }
        if(f) cout << "NO\n";
        else{
            f = 0;
            for(int i=n-1;i>=0;i--){
                int x = i+1;
                int y = v[i];
                while(x%2==0) x /= 2;
                while(y%2==0) y /= 2;
                if(x != y){
                    f = 1;
                    break;
                }
            }
            if(f) cout << "NO\n";
            else cout << "YES\n";
        }
    }
}


