int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
		cin >> n;
		map<int,int> mp;
		for(int i=0;i<n;i++){
			int x; 
            cin >> x;
			mp[x]++;
		}
		int mx = 0;
		for(auto &[x,f] : mp) mx = max(mx,f);
		int p = 0,h = mx,ne = n-mx;
		while(ne>0){
			p++;
			int t = min(h,ne);
			p += t;
			ne -= t;
			h *= 2;
		}
		cout << p << '\n';

    }
}


