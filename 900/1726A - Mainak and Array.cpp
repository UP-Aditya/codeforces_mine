#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        if(n==1) cout << 0 << '\n';
        else{
        int f = LLONG_MIN;

        for(int i=0;i<n-1;i++){
            f = max(f,v[n-1]-v[i]);
        }
        for(int i=1;i<n;i++){
            f = max(f,v[i]-v[0]);
        }
        for(int i=0;i<n-1;i++){
            f = max(f,v[i]-v[i+1]);
        }
        cout << f << '\n';
    }
}
}


