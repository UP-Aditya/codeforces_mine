int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int s= 0;
        int df= 1e18;
        for(int i=0;i<n;i++){
            s += v[i];
            df = min(df,s/(i+1));
            cout << df << " ";
        }
        cout << '\n';

    }
}


