int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int l,r,x;
        cin >> l >> r >> x;
        int f = r/x+r%x;
        int m = r/x*x-1;
        if(m>=l) f = max(f,m/x+m%x);
        cout << f << '\n';

    }
}


