int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int x,n;
        cin >> x >> n;
        int p = n%4;
        int f;
        if(p==0) f = 0;
        else if(p==1) f = -n;
        else if(p==2) f = 1;
        else f = n+1;

        if(x%2==0){
            cout << x+f << '\n';
        }
        else cout << x-f << '\n';

    }
}


