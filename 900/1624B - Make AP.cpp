bool ff(int a,int b,int c){
    if((2*b-c)%a==0 && (2*b-c)/a > 0) return true;
    if((a+c)%(2*b)==0 && (a+c)/(2*b) > 0) return true;
    if((2*b-a)%c==0 && (2*b-a)/c > 0) return true;
    return false;
}
int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b,c;
        cin >> a >> b >> c;
        bool p = ff(a,b,c);
        if(p) cout << "YES\n";
        else cout << "NO\n";
        
    }
}


