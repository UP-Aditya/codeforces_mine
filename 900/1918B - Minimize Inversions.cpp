int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n),vv(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        for(int i=0;i<n;i++){
            cin >> vv[i];
        }
        vector<pair<int,int>> vp;
        for(int i=0;i<n;i++){
            vp.push_back({v[i],vv[i]});
        }
        sort(vp.begin(),vp.end());
        for(auto &i : vp){
            cout << i.first << " ";
        }
        cout << '\n';
        for(auto &i : vp){
            cout << i.second << " ";
        }
        cout << '\n';


    }
}


