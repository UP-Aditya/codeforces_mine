int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x,y;
        cin >> n >> x >> y;
        int p = max(x,y);
        if((x&&y) || (!x&&!y) || ((n-1)%p!=0)){
            cout << -1 << '\n';
            continue;
        }
        for(int i=2;i<=n;i+=p){
            for(int j=1;j<=p;j++){
                cout << i << " ";
            }
        }
        cout << '\n';
    }
}


