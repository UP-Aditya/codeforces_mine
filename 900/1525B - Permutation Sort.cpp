int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int mx = INT_MIN,mn = INT_MAX;
        for(int i=0;i<n;i++){
            cin >> v[i];
            mx = max(v[i],mx);
            mn = min(v[i],mn);
        }
        int f = 0;
        int op = 3;
        for(int i=1;i<n-1;i++){
            if(v[i]!=i+1){
                f = 1;
            }
        }
        if(f==0){
            if(v[0]==mn && v[n-1]==mx) op -= 3;
            else if(v[n-1]==mn && v[0]==mx) op -= 0;
        }
        else{
            if(v[0]==mn && v[n-1]==mx) op -= 2;
            else if(v[0]==mn || v[n-1]==mx) op -= 2;
            else if(v[n-1]==mn && v[0]==mx) op -= 0;
            else op -= 1;
        }
        cout << op << '\n';

    }
}


