int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b,n;
        cin >> a >> b >> n;
        vector<int> v(n);
        int c = 0;
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        for(int i=0;i<n;i++){
            c += min(v[i],a-1);
        }
        cout << b+c << '\n';
    }
}


