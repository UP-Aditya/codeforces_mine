int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,x,y;
        cin >> n >> x >> y;
        string s;
        cin >> s;
        x = abs(x);
        y = abs(y);
        for(int i=0;i<n;i++){
            if(s[i]=='4'){
                if(max(x,y)==x){
                    x--;
                }
                else{
                    y--;
                }
            }
            else{
                x--;
                y--;
            }
        }
        if(x<=0 && y<=0) cout << "YES\n";
        else cout << "NO\n";

    }
}


