int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int f1 = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]!=0){
                f1 = 1;
            }
        }
        if(f1==0){
            cout << 0 << '\n';
        }
        else{
            int p,q,f2=0;
            for(int i=0;i<n;i++){
                if(v[i]!=0){
                    p = i;
                    break;
                }
            }
            for(int i=n-1;i>=0;i--){
                if(v[i]!=0) {
                    q = i;
                    break;
                }
            }
            for(int i=p+1;i<q;i++){
                if(v[i]==0){
                    f2 = 1;
                    break;
                }
            }
            if(f2==1) cout << 2 << '\n';
            else cout << 1 << '\n';
        }
    }
}


