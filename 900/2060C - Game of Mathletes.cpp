int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        unordered_map<int,int> mp;
        for(auto &i : v){
            mp[i]++;
        }
        int scr = 0;
        for(int i=0;i<n;i++){
            int x = v[i];
            int y = k-x;
            if(x==y){
                if(mp[x]>=2){
                 scr++;
                 mp[x] -= 2;
                }
            }
            else if(mp[x]>0 && mp[y]>0){
                scr++;
                mp[x]--;
                mp[y]--;
            }
        }
        cout << scr << '\n';
        

    }
}


