    int t;
    cin >> t;
    while(t--){
        string s;
        cin >> s;
        int c1 = 0,c0 = 0;
        for(int i=0;i<s.size();i++){
            if(s[i]=='0') c0++;
            else c1++;
        }
        if(min(c1,c0)%2==0) cout << "NET\n";
        else cout << "DA\n";
        
    }
