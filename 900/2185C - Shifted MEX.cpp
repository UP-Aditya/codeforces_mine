int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        set<int> s;
        for(int i=0;i<n;i++){
            int x;
            cin >> x;
            s.insert(x);
        }
        int mx = 0;
        int c = 0;
        int p = 1e18;
        for(auto &i : s){
            if(i==p+1){
                c++;
            } 
            else c = 1;
            mx = max(mx,c);
            p = i;
        }
        cout << mx << endl;

    }
}


