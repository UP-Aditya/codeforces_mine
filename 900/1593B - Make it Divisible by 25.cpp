int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s = to_string(n);
        int f1 = 0, f2 = 0;
        int c1 = 0, c2 = 0;
        if(n%25==0) cout << 0 << '\n';
        else{
        for(int i=s.size()-1;i>=0;i--){
            if(s[i]=='0' && f1==0){
                f1 = 1;
            }
            else if((s[i]=='0' || s[i]=='5') && f1==1){
                break;
            }
            else c1++;
        }
        for(int i=s.size()-1;i>=0;i--){
            if(s[i]=='5' && f2==0){
                f2 = 1;
            }
            else if((s[i]=='2' || s[i]=='7') && f2==1){
                break;
            }
            else c2++;
        }
        cout << min(c1,c2) << '\n';

    }
}
}


