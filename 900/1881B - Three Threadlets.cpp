int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        vector<int> v(3);
        for(int i=0;i<3;i++){
            int x;
            cin >> x;
            v[i] = x;
        }
        sort(v.begin(),v.end());
        int a = v[0];
        int b = v[1];
        int c = v[2];
        if(a==b && b==c) cout << "YES\n";
        else if(b%a==0 && c%a==0 && ((b+c)/a -2 <= 3)) cout << "YES\n";
        else cout << "NO\n";

    }
}


