int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int s = 0;
        int c1 = 0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
            s += v[i];
            if(v[i] == 1) c1++;
        }
        if(n==1){
            cout << "NO\n";
            continue;
        }
        if((n + (n+1)/2)  <= s && (c1 <= s/2)) cout << "YES\n";
        else cout << "NO\n";
    }
}


