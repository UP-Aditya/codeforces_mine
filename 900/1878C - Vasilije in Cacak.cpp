int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k,x;
        cin >> n >> k >> x;
        int st = (n*(n+1))/2;
        int smin = (k*(k+1))/2;
        int smax = st - ((n-k)*(n-k+1))/2;
        if(x>=smin && x<=smax) cout << "YES\n";
        else cout << "NO\n";
        

    }
}


