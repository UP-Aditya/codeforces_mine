int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin>>n;
        string s;
        cin>>s;
        if(n&1){
            cout<<"NO\n";
            continue;
        }
        stack<char>st;
        for(auto  i:s){
            if(!st.empty() && st.top()==i)
                st.pop();
            else
                st.push(i);
        }
        if(st.empty()) cout<<"YES\n";
        else cout<<"NO\n";

    }
}


