int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m,k;
        cin >> n >> m >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            v[i] = i+1;
        }
        vector<int> p;
        sort(v.rbegin(),v.rend());
        int l= -1,r=n-1;
        for(int i=n-1;i>=0;i--){
            if(v[i]>m){
                l = i;
                break;  
            }
        }
        for(int i=0;i<=l;i++){
            p.push_back(v[i]);
        }
        for(int i=r;i>l;i--){
            p.push_back(v[i]);
        }
        for(auto &i : p){
            cout << i << " ";
        }
        cout << '\n';



    }
}


