int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        string s="";
        map<char,int> mp;
        for(int i=0;i<n;i++){
            for(char c='a';c<='z';c++){
                if(mp[c]==v[i]){
                    s += c;
                    mp[c]++;
                    break;
                }
            }
        }
        cout << s << '\n';

    }
}


