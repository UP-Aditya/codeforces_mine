int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<pair<int,int>> a(n);
        vector<int> b(n);
        for(int i=0;i<n;i++){
            cin >> a[i].first;
            a[i].second = i;
        }
        for(int i=0;i<n;i++){
            cin >> b[i];
        }
        sort(a.begin(),a.end());
        sort(b.begin(),b.end());
        vector<int> df(n);
        for(int i=0;i<n;i++){
             df[a[i].second]= b[i];
        }
        for(auto &i : df) cout << i << " ";
        cout << endl;
      
    }
}


