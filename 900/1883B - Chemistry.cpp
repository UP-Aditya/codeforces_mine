int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        string s;
        cin >> s;
        int co = 0;
        map<char,int> m;
        for(auto &i : s){
            m[i]++;
        }
        for(auto &i : m){
            if(i.second%2!=0){
                co++;
            }
        }
        if(co > k+1) cout << "NO\n";
        else cout << "YES\n";
    }
}


