int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int k;
        cin >> k;
        vector<int> v(n*k);
        for(int i=0;i<n*k;i++){
            cin >> v[i];
        }
        int s = 0;
        int p = n/2+1;
        int f = n*k - p;
        for(int i=0;i<k;i++){
            s += v[f];
            f -= p;
        }
        cout << s << '\n';

    }
}


