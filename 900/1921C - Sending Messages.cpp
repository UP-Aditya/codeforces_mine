int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,f,a,b;
        cin >> n >> f >> a >> b;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int m = 0;
        if(v[0]>0){
            if(v[0]*a > b){
                f -= b;
            }
            else
            f -= a*v[0];
            m++;
        }
        for(int i=1;i<n;i++){
            if(f<=0) break;
            if((v[i]-v[i-1])*a > b){
                f -= b;
            }
            else{
                f -= (v[i]-v[i-1])*a;
            }
            m++;
        }
        if(m>=n && f>0) cout << "YES\n";
        else cout << "NO\n";
    }
}


