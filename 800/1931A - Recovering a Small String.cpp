int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string p = "";
        for(int i=1;i<=26;i++){
            for(int j=1;j<=26;j++){
                for(int k=1;k<=26;k++){
                    if(i+j+k == n){
                        p += char('a'+i-1);
                        p += char('a'+j-1);
                        p += char('a'+k-1);
                        goto done;
                    }
                }
            }
        }
        done:
        cout << p << endl;

    }
}


