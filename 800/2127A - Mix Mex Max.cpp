int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++) cin >> v[i];
        set<int> s(v.begin(),v.end());
        s.erase(-1);
        if(s.size()<=1 && !s.count(0)) cout << "YES\n";
        else cout << "NO\n";
    }
}

