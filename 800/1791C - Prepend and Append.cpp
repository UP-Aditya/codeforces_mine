int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int i = 0;
        int j = n-1;
        int c = 0;
        while(i<=j){
            if(s[i]!=s[j]){
                c += 2;
                i++;
                j--;
            }
            else break;
        }
        cout << n - c << '\n';
    }
}


