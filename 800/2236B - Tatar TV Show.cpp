int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        string s;
        cin >> s;
        int f = 0,fg=0;
        for(int i=0;i<k;i++){
            int f = 0;
            for(int j=i;j<n;j+=k){
                if(s[j]=='1') f++;
            }
            if(f%2){
                fg = 1;
                break;
            }
        }
        if(fg) cout << "NO\n";
        else cout << "YES\n";

    }
}


