int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int p = v[0];
        if(v.size()%2!=0){
            for(int i=1;i<n;i++){
                p = p^v[i];
            }
            cout << p << '\n';
        }
        else{
            for(int i=1;i<n;i++){
                p = p^v[i];
            }
            if(p==0) cout << 1 << '\n';
            else cout << -1 << '\n';
        }

    }
}


