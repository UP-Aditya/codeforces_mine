int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b;
        cin >> a >> b;
        int  x = 0,y = 0;
        int c = 1;
        int f = 1;
        int ff = 1;
        int df = 0;
        while(1){
            if(ff) x += c;
            else y += c;
            if((x<=a && y<=b) || (x<=b && y<=a)) df = max(df,f);
            else break;
            f++;
            if(ff) ff = 0;
            else ff = 1;
            c *= 2;
        }
        cout << df << '\n';

    }
}


