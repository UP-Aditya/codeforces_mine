int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string s;
        cin >> s;
        vector<int> p = {1,2,3,4,5,6,7,8};
        vector<char> q = {'a','b','c','d','e','f','g','h'};
        for(int i=0;i<q.size();i++){
            for(int j=0;j<p.size();j++){
                if(s[0]==q[i] && (s[1]-'0')==p[j]) continue;
                if(s[0]==q[i] || (s[1]-'0') == p[j]){
                    cout << q[i] << p[j] << '\n';
                }
            }
        }
        cout << '\n';

    }
}


