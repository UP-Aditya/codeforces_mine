int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin>>v[i];
        }
        vector<int> p = v;
        sort(p.begin(),p.end());
        for(int i=0;i<n-2;i++){
            for(int j=i+1;j<n-1;j++){
                for(int k =j+1;k<n;k++){
                    if(v[i]<=v[k] && v[j]>v[k]){
                        swap(v[j],v[k]);
                    }
                }
            }
        }
        if(v==p){
            cout<<"Yes\n";
        }
        else cout<<"No\n";
    }
}


