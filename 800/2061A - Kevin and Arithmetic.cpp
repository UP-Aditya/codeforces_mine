int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int ce=0,co=0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]%2==0) ce++;
            else co++;
        }
        if(ce==0) cout << co-1 << '\n';
        // else if(co==0) cout << 1 << '\n';
        else cout << co+1 << '\n';

    }
}


