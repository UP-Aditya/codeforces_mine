int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        vector<int> v(7);
        for(int i=0;i<7;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        for(int i=0;i<6;i++){
            v[i] *= (-1);
        }
        cout << accumulate(v.begin(),v.end(),0LL) << '\n';

    }
}


