int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        vector<int> df1,df2,df3,df;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]%6==0) df.push_back(v[i]);
            else if(v[i]%2==0) df2.push_back(v[i]);
            else if(v[i]%3==0) df3.push_back(v[i]);
            else if(v[i]%6) df1.push_back(v[i]);
        }
        for(auto &i : df) cout << i << " ";
        for(auto &i : df3) cout << i << " ";
        for(auto &i : df1) cout << i << " ";
        for(auto &i : df2) cout << i << " ";
        cout << endl;


    }

}


