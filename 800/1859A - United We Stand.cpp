int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        vector<int> b;
        vector<int> c;
        int mn = INT64_MAX;
        for(int i=0;i<n;i++){
            cin >> v[i];
            mn = min(mn,v[i]);
        }
        sort(v.begin(),v.end());
        if(v[0]==v[n-1]){
            cout << -1 << '\n';
        }
        else{
        for(int i=0;i<n;i++){
            if(v[i]==mn){
               b.push_back(v[i]);
            }
            else c.push_back(v[i]);
        }
        cout << b.size() << " " << c.size();
        cout << '\n';
        for(int i=0;i<b.size();i++) cout << b[i] << " ";
        cout << '\n';
        for(int i=0;i<c.size();i++) cout << c[i] << " ";
        cout << '\n';
    }

}
}


