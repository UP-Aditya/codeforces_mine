int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int ec=0,oc=0;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]%2==0) ec++;
            if(v[i]%2) oc++;
        }
        if(ec && oc){
            sort(v.begin(),v.end());
        }
        for(int i=0;i<n;i++){
                cout << v[i] << " ";
            }
            cout << '\n';
    }
}


