int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        vector<int> ans(n,2);
        int f = 0;
        int mx = INT_MIN;
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]>mx){
                mx = v[i];
            }
        }
        for(int i=1;i<n;i++){
            if(v[i]!=v[i-1]){
                f = 1;
                break;
            }
        }
        if(f==0) cout << "NO\n";
        else{
            cout << "YES\n";
            for(int i=0;i<n;i++){
                if(v[i]==mx){
                    ans[i] = 1;
                }
                cout << ans[i] << " ";
            }
            cout << '\n';
        }

    }
}


