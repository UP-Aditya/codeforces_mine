int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,m;
        cin >> n >> m;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        int x = 0;
        int j = n-1;
        while(1){
            x += v[j]*m;
            j--;
            m--;
            if(m==0 || j==-1) break;
        }
        cout << x << '\n';

    }
}


