int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        string s;
        cin >> s;
        map<int,char> mp;
        int f = 0;
        for(int i=0;i<n;i++){
            if(mp.find(v[i])==mp.end()){
                mp[v[i]] = s[i];
            }
            else if(mp[v[i]]==s[i]) continue;
            else{
                f = 1;
                break;
            }
        }
        if(f) cout << "NO\n";
        else cout << "YES\n";

    }
}


