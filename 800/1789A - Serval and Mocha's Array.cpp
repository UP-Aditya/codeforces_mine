int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        bool f = false;
        for(int i=0;i<n;i++){
            for(int j=i+1;j<n;j++){
                if(gcd(v[i],v[j])<=2){
                    f = true;
                    break;
                }
            }
        }
        if(f) cout << "Yes\n";
        else cout << "No\n";
    }
}


