int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t; 
    cin >> t;
    while(t--){
        int n; 
        cin >> n;
        string s; 
        cin >> s;
        vector<int> v(n);
        int l=1,r=n;
        for(int i=n-2;i>=0;i--){
            if(s[i]=='<') v[i+1] = l++;
            else v[i+1] = r--;
        }
        v[0] = l;
        for(auto &i : v) cout << i << " ";
        cout << '\n';
    }
}


