int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int x = 1;
        vector<vector<int>> v(n,vector<int> (n));
        for(int i=0;i<n;i++){
            for(int j=0;j<n;j++){
                v[i][j] = x++;
            }
        }
        if(n==1){
            cout << 1 << '\n';
        }
        else if(n==2) cout << 9 << '\n';
        else{
            int p = 0;
            for(int i=0;i<n;i++){
                for(int j=0;j<n;j++){
                    int f = v[i][j];
                    if(i>0){
                        f += v[i-1][j];
                    }
                    if(j>0){
                        f += v[i][j-1];
                    }
                    if(i<n-1){
                        f += v[i+1][j];
                    }
                    if(j<n-1){
                        f += v[i][j+1];
                    }
                    p = max(f,p);
                }
            }
            cout << p << '\n';
        }
    }
}


