int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int a,b,c;
        cin >> a >> b >> c;
        int s = a + b + c;
        int p = s/3;
        int q = abs(a-p) + abs(b-p) + abs(c-p);
        int f = abs(a-b) + abs(a-c);
        int g = abs(b-a) + abs(b-c);
        int h = abs(a-c) + abs(b-c);
        int ff = min(q,f);
        int gg = min(g,h);
        cout << min(ff,gg) << '\n';


    }
}


