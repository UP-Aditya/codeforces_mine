int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        int x;
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        x = v[0];
        int f = 0;
        unordered_set<int> s;
        s.insert(x);
        for(int i=1;i<n;i++){
            if(s.find(v[i]+1) != s.end()){
                s.insert(v[i]);
            }
            else if(s.find(v[i]-1) != s.end()){
                s.insert(v[i]);
            }
            else{
                f = 1;
                break;
            }
        }
        if(!f) cout << "YES\n";
        else cout << "NO\n";


    }
}


