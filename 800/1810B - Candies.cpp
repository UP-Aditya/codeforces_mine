int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v;
        if(n%2==0) cout << -1 << '\n';
        else{
            while(n!=1){
                if((n-1)%2==0 && ((n-1)/2)%2 != 0){
                    v.push_back(2);
                    n--;
                    n /= 2;
                }
                else{
                    v.push_back(1);
                    n++;
                    n /= 2;
                }
            }
            reverse(v.begin(),v.end());
            cout << v.size() << '\n';
            for(auto &i : v){
                cout << i << " ";
            }
            cout << '\n';
        }

    }
}


