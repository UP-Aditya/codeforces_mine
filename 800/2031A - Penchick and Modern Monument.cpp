int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        map<int,int> mp;
        int p = 0;
        for(auto &i : v){
            mp[i]++;
        }
        for(auto &i : mp){
            p = max(p,i.second);
        }
        cout << n-p << '\n';

    }
}


