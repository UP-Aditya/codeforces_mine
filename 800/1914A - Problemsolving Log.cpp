int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        unordered_map<char,int> mp;
        for(auto &i : s){
            mp[i]++;
        }
        int df = 0;
        for(auto &i : mp){
            if(i.second >= (int)i.first - 64) df++;
        }
        cout << df << '\n';
    }
}


