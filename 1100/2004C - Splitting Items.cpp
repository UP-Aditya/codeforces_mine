int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.rbegin(),v.rend());
        int s = 0;
        for(int i=0;i<n;i++){
            if(i%2==0) s += v[i];
            else s -= v[i];
        }
        for(int i=1;i<n;i+=2){
            int x = v[i-1] - v[i];
            int j = min(x,k);
            s -= j;
            k -= j;
        }
        cout << s << '\n';
    }
}

