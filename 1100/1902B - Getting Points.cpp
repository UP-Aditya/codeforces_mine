int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,p,l,t;
        cin >> n >> p >> l >> t;
        int cp = 0;
        int x = n/7;
        if(n%7){
            x++;
        }
        int mx = x/2;
        int c = 0;
        if(mx*(l+t*2) >= p){
            int r = (p+(l+t*2)-1)/(l+t*2);
            cout << n-r << '\n';
        }
        else{
            c += mx;
            cp += mx*(l+t*2);
            if(x%2){
                c++;
                cp += (l+t);
            }
            if(cp<p){
                c += (p-cp+l-1)/l;
            }
            cout << n-c << '\n';
        }

    }
}


