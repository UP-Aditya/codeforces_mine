#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        vector<int> pre(n+1,0);
        for(int i=0;i<n;i++){
            pre[i+1] = pre[i] + v[i];
        }
        int mx = 0;
        for(int i=0;i<=k;i++){
            int l = 2*i;
            int r = n-(k-i);
            if(l>r) continue;
            int cs = pre[r]-pre[l];
            mx = max(mx,cs);
        }

        cout << mx << '\n';
    }
}


