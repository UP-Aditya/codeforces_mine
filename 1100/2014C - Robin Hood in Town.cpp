#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        if(n<=2){
            cout << -1 << '\n';
            continue;
        }
        int s = accumulate(v.begin(),v.end(),0LL);
        auto check = [&](int mid)->bool{
            int c = 0;
            for(auto &i : v){
                if(i*2*n<s+mid) c++;
            }
            return (c>n/2);

        };
        int l=0,h=1e18;
        int df = -1;
        while(l<=h){
            int mid = l + (h-l)/2;
            if(check(mid)){
                df= mid;
                h = mid-1;
            }
            else{
                l = mid+1;
            }
        }
        cout << df << '\n';

    }
}


