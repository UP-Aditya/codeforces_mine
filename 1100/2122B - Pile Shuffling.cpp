int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    
    while(t--){
        int op = 0;
        int n;
        cin >> n;
        while(n--){
        int a,b,c,d;
        cin >> a >> b >> c >> d;
        if(b>d){
            op = op + a + abs(b-d);
        }
        else{
            if(a>c){
                op += abs(a-c);
            }
        }
        
    }
    cout << op << '\n';
}
}


