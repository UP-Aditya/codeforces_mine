int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<vector<char>> v(n,vector<char>(n,'D'));
        int x = k;
        if(k == n*n-1){
            cout << "NO\n";
            continue;
        } 
        else{
            cout << "YES\n";
        }
        for(int i=0;i<n;i++){
            for(int j=0;j<n;j++){
                if(k>0){
                    v[i][j] = 'U';
                    k--;
                }
            }
        }
        int j = 0;
        while(j<n){
            if(v[n-1][j] != 'U'){
                v[n-1][j] = 'R';
            }
            j++;
        }
        if(n*n != x){
            v[n-1][n-1] = 'L';
        }
        for(int i=0;i<n;i++){
            for(int j=0;j<n;j++){
                cout << v[i][j];
            }
            cout << "\n";
        }
    }

}

