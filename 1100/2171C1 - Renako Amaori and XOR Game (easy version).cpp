int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin>>n;
        vector<int>v(n);
        vector<int>p(n);
        for(int i =0;i<n;i++){
            cin>>v[i];
        }
        for(int i =0;i<n;i++){
            cin>>p[i];
        }
        int x=0,y=0;
        for(int i =0;i<n;i++){
            x^=v[i];
            y^=p[i];
        }
        if(x==y){
            cout<<"Tie\n";
            continue;
        }
        else{
            for(int i = n-1;i>=0;i--){
                if(v[i]!=p[i]){
                    if(i%2){
                        cout<<"Mai\n";
                        break;
                    }
                    else{
                        cout<<"Ajisai\n";
                        break;
                    }
                }
            }
        }

    }
}


