#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int s,k,m;
        cin >> s >> k >> m;
        int x = m%k;
        int f = m/k;
        int df = 0;
        if(s<=k || f%2==0){
            df = max(s-x,0LL);
        }
        else if(f%2){
            df = max(k-x,0LL);
        }
        cout << df << '\n';
    }
}


