#include<bits/stdc++.h>
using namespace std;
#define int long long
// :__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL); cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n; 
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int tot = accumulate(v.begin(),v.end(),0LL);
        int p = 0,f = 0;
        for(int i=0;i<n-1;i++){
            p += v[i];
            tot -= v[i];
            f = max(f,gcd(p,tot));
        }
        cout << f << "\n";
    }
}


