#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k,x;
        cin >> n >> k >> x;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        sort(v.begin(),v.end());
        vector<int> p(n+1,0);
        for(int i=0;i<n;i++){
            p[i+1] = p[i]+v[i];
        }
        int ans = -1e18;
        for(int i=0;i<=k&&i<=n;i++){
            int r = n-i;              
            int df = min(x,r);       
            int c = p[r];
            int ne = p[r]-p[r-df];
            c -= 2*ne;
            ans = max(ans,c);
        }
        cout<<ans<<"\n";
    }
}


