int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v(n+1);
        if(k%2==0){
            for(int i=1;i<=n;i++){
                if(i==n-1){
                    v[i] = n;
                }
                else{
                    v[i] = n-1;
                }
            }
        }
       else{
            for(int i=1;i<=n;i++){
                if(i==n){
                    v[i] = n-1;
                }
                else{
                    v[i] = n;
                }
            }
        }
        for(int i=1;i<=n;i++){
            cout << v[i] << " ";
        }
        cout << '\n';


    }
}


