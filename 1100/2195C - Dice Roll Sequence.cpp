int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int c = 0;
        if(n==1){
            cout << 0 << endl;
        }
        else if(n==2){
            if((v[0]==v[1]) || (7-min(v[0],v[1]) == max(v[0],v[1]))) cout << 1 << endl;
            else cout << 0 << endl;
        }
        else{
        for(int i=0;i<n-1;i++){
            int f = 0;
            if(v[i]==v[i+1]) f=1;
            if(v[i]+v[i+1]==7) f=1;
            if(f){
                c++;
                i++; 
            }
        }
        cout << c << endl;
    }

    }
}


