int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s,r;
        cin >> s>> r;
        int c0=0,c1=0;
        for(auto &i : s){
            if(i=='0') c0++;
            else c1++;
        }
        int f =0;
        for(int i=0;i<r.size();i++){
            if(!c0 || !c1){
                f = 1;
                break;
            }
            else if(r[i]=='0') c1--;
            else if(r[i]=='1') c0--;
        }
        if(f) cout << "NO\n";
        else cout << "YES\n";

    }
}


