int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<vector<char>> v(2,vector<char>(n));
        for(int i=0;i<2;i++){
            for(int j=0;j<n;j++){
                cin >> v[i][j];
            }
        }
        int c = 0;
        for(int i=0;i<1;i++){
            for(int j=0;j<n;j++){
                if(v[i][j]==v[i+1][j]) continue;
                else if(v[i][j]!=v[i+1][j] && v[i][j]==v[i][j+1] && j+1<n){
                    if(v[i+1][j]!=v[i+1][j+1]){
                        c++;
                    }
                    j++;
                }
                else c++;
            }
        }
        cout << c << '\n';
    }
}


