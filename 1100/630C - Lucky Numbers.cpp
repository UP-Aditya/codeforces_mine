#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    vector<int> p(56,0);
    p[0] = 2;
    for(int i=1;i<56;i++){
        p[i] = p[i-1]+(1LL<<(i+1));
    }
    
    int t=1;
    // cin >> t;
    while(t--){
        int n;
        cin >> n;
        cout << p[n-1] << '\n';
    }
}


