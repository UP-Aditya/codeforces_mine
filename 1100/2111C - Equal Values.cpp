int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++)
         cin >> v[i];
        int f = LLONG_MAX;
        int i = 0;
        while(i<n){
            int j = i;
            while(j<n && v[j]==v[i]) j++;
            f = min(f,(i+(n-j))*v[i]);
            i = j;
        }
        cout << f << "\n";
    }
}


