int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,s;
        cin >> n >> s;
        int sum = 0;
        int c1=0,c0=0,c2=0;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
            if(v[i]==0) c0++;
            else if(v[i]==1) c1++;
            else c2++;
        }
        sum = c1*1 + c2*2;
        if(sum > s || sum+1 == s){
            for(int i=0;i<c0;i++){
                cout << 0 << " ";
            }
            for(int i=0;i<c2;i++){
                cout << 2 << " ";
            }
            for(int i=0;i<c1;i++){
                cout << 1 << " ";
            }
            cout << '\n';
        }
        else cout << -1 << '\n';



    }
}


