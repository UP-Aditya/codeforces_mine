int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> p(n);
        map<int,int> df;
        for(int i=0;i<n;i++){
            cin >> p[i];
            df[p[i]] = i;
        }
        vector<int> a(n);
        for (int i=0;i<n;i++){
            cin >> a[i];
        }
        if(p==a){
            cout << "YES\n";
            continue;
        }
        int f = 0;
        for(int i=1;i<n;i++){
            if(a[i]!=a[i-1]){
                if(df[a[i]]<df[a[i-1]]){
                    f = 1;
                    break;
                }
            }
        }
        if(!f) cout << "YES\n";
        else cout << "NO\n";
    }
}


