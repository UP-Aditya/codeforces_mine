int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n, l, r;
        cin >> n >> l >> r;
        l--;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> temp1(v.begin()+l,v.end());
        sort(temp1.begin(),temp1.end());

        int sum1 = 0;
        for(int i=0;i<r-l;i++){
            sum1 += temp1[i];
        }
        vector<int> temp2(v.begin(),v.begin()+r);
        sort(temp2.begin(),temp2.end());
        int sum2 = 0;
        for(int i=0;i<r-l;i++){
            sum2 += temp2[i];
        }
        cout << min(sum1,sum2) << '\n';
    }

}

