int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,q;
        cin >> n >> q;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        vector<int> x(q);
        for(int i=0;i<q;i++){
            cin >> x[i];
        }
        set<int> st;
        for(int i=0;i<q;i++){
            if(st.find(x[i]) != st.end()){
                continue;
            }
            else{
                st.insert(x[i]);
                for(int j=0;j<n;j++){
                if(v[j]%(1<<x[i]) == 0){
                    v[j] = v[j] + (1<<(x[i]-1));
                }
            }
            }
        }
        for(int i=0;i<n;i++){
            cout << v[i] << " ";
        }
        cout << '\n';


    }
}


