#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n, k;
        cin >> n >> k;
        vector<int> v(n),p(n);
        for(int i=0;i<n;i++) cin >> v[i];
        for(int i=0;i<n;i++) cin >> p[i];

        int sa = 0;
        int bb = 0;
        int ff = 0;

        for(int i=0;i<min(n,k);i++){
            sa += v[i];
            bb = max(bb,p[i]);
            int rem = k-(i+1);
            ff = max(ff,sa+bb*rem);
        }

        cout << ff << '\n';
    }
}


