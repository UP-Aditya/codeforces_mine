int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i];
        }
        int csm = v[0];
        int msm = v[0];
        int f = 0;
        if(n==1) cout << v[0] << '\n';
        else{
            int lp = v[0]&1;
            for(int i=1;i<n;i++){
                int p1 = v[i]&1;
                // int p2 = v[i-1]&1;
                if(p1==lp){
                    msm = max(msm,csm);
                    csm = v[i];
                }
                else{
                    csm = max(csm+v[i],v[i]);
                    
                }
                lp = p1;
                msm = max(msm,csm);
            }
            msm = max(msm,csm);
            cout << msm << '\n';
        }

    }
}


