#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);
    set<int> c;
    for(int i=1;i<=10000;i++){
        c.insert(i*i*i);
    }

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        int p = (int)cbrt(n);
        int f = 0;
        for(int i=1;i<=p;i++){
            int x = i*i*i;
            if(c.count(n-x)){
                f = 1;
                break;
            }
        }
        if(f) cout << "YES\n";
        else cout << "NO\n";
        
    }
}


