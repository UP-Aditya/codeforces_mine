int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int n,k;
    cin >> n >> k;
    string s;
    cin >> s;
    unordered_map<char,int> lp;
    unordered_set<char> active;

    for(int i=0;i<n;i++){
        lp[s[i]] = i;
    }
    for(int i=0;i<n;i++){
        active.insert(s[i]);
        if(active.size()>k){
            cout << "YES\n";
            return 0;
        }
        if(lp[s[i]]==i){
            active.erase(s[i]);
        }
    }
    cout << "NO\n";
}



