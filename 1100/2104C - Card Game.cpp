int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        if(s[0]=='A'){
            if(s[n-1]=='A'){
                cout << "Alice\n";
            }
            else{
                int f = 0;
                for(int i=1;i<n-1;i++){
                    if(s[i]=='B'){
                        f = 1;
                        break;
                    }
                    else continue;
                }
                if(f) cout << "Bob\n";
                else cout << "Alice\n";

            }
        }
        else{
            if(s[n-1]=='B') cout << "Bob\n";
            else{
                if(s[n-2]=='B') cout << "Bob\n";
                else cout << "Alice\n";
            }
        }
        

    }
}


