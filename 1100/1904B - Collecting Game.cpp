int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<pair<int,int>> v(n);
        for(int i=0;i<n;i++){
            cin >> v[i].first;
            v[i].second = i;
        }
        sort(v.begin(),v.end());
        vector<int> pre(n);
        pre[0] = v[0].first;
        
        for(int i=1;i<n;i++){
            pre[i] = pre[i-1]+v[i].first;
        }
        vector<int> df(n);
        df[v[n-1].second] = n-1;
        for(int i=n-2;i>=0;i--){
            if(pre[i]>=v[i+1].first){
                df[v[i].second] = df[v[i+1].second];
            } 
            else{
                df[v[i].second] = i;
            }
        }
        for(int i=0;i<n;i++){
            cout << df[i] << " ";
        }
        cout << endl;
    }

    }


