int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        string s;
        cin >> s;
        int c=0;
        stack<int> st;
        for(int i=0;i<n;i++){
            if(i%2){
                if(s[i]=='('){
                    st.push(i);
                }
                else if(s[i]==')'){
                    c += i - st.top();
                    st.pop();
                }
            }
            else{
                if(!st.empty()){
                    c += i-st.top();
                    st.pop();
                }
                else{
                    st.push(i);
                }
            }
        }
        cout << c << '\n';

    }
}


