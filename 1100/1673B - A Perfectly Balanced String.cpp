int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        string s;
        cin >> s;
        int n = s.size();
        int f = 0;
        set<char> st(s.begin(),s.end());
        int k = st.size();
        vector<int> pp(26,-1);
        for(int i=0;i<n;i++){
            if(pp[s[i]-'a'] != -1){
                if(i-pp[s[i]-'a'] < k){
                    f = 1;
                    break;
                }
            }
            pp[s[i]-'a'] = i;  // &^(
        }
        if(f) cout << "NO\n";
        else cout << "YES\n";

    }
}


