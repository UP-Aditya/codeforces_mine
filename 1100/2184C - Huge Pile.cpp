int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        int c = 0;
        int p = 1;
        int f = 0;
        if(n==k) cout << 0 << '\n';
        else if(k>n) cout << -1 << '\n';
        else{
            while(1){
                int x1 = n/p;
                int x2 = x1;
                if(n%p != 0) x2++; 
                if(x1==k || x2==k){
                    f = 1;
                    break;
                }
                if(x2<k) break;
                c++;
                p *= 2;
                }
            if(f) cout << c << '\n';
            else cout << -1 << '\n';
        }    

    }
}


