int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t=1;
    // cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        int c = 0;
        map<int,int> mp;
        for(int i=2;i<=1e5 && c<k-1;i++){
            while(n%i==0 && c<k-1){
                mp[i]++;
                c++;
                n /= i;
            }
        }
        c = 0;
        for(auto &i : mp){
            c += i.second;
        }
        if(c==k-1 && n!=1){
            for(auto &i : mp){
                int x = i.second;
                while(x--){
                    cout << i.first << ' ';
                }
            }
            cout << n << '\n';
        }
        else cout << -1 << '\n';
    }
}


