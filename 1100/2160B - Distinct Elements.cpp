#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        long long n;
        cin >> n;
        vector<int> v(n+1);
        for(int i=1;i<=n;i++){
            cin >> v[i];
        }
        int num = 0;
        vector<int> df(n+1);
        df[1] = ++num;
        for (int i=2;i<=n;i++){
            int x = v[i]-v[i-1];
            if(x==i)
                df[i] = ++num;
            else
                df[i] = df[i-x];
        }
        for(int i=1;i<=n;i++){
            cout << df[i] << " ";
        }
        cout << "\n";

    }
}


