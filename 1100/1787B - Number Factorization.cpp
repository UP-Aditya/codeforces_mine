int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        map<int,int> mp;
        while(n%2==0){
            mp[2]++;
            n /= 2;
        }
        for(int i=3;i*i<=n;i+=2){
            while(n%i==0){
                mp[i]++;
                n /= i;
            }
        }
        if(n>1)  mp[n]++;
        vector<pair<int,int>> vv;
        int m = 1;
        for(auto &i : mp){
            vv.push_back({i.second,i.first});
            m *= i.first;
        }
        sort(vv.begin(),vv.end());
        int p = 0,x=0;
        for(int i=0;i<vv.size();i++){
            x += m*(vv[i].first-p);
            p += (vv[i].first-p);
            m /= vv[i].second;
        }
        cout << x << '\n';
    }
}


