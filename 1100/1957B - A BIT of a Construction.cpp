#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: chahat

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k;
        cin >> n >> k;
        vector<int> v;
        if(n==1){
            cout << k << endl;
            continue;
        }
        int x = 63 - __builtin_clzll(k);
        v.push_back((1LL << x)-1);
        v.push_back(k - ((1LL << x)-1));
        if(v.size()<n){
            int x = n-v.size();
            while(x--){
                v.push_back(0);
            }
        }
        for(auto &i : v) cout << i << " ";
        cout << '\n';
    }
}


