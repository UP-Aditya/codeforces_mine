#include<bits/stdc++.h>
using namespace std;
#define int long long
//:__: aditya_up62

int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n,k,a,b;
        cin >> n >> k >> a >> b;
        vector<int> x(n+1),y(n+1);
        for(int i=1;i<=n;i++){
            cin >> x[i] >> y[i];
        }
        int ans = abs(x[a]-x[b]) + abs(y[a]-y[b]);
        int mna = 1e18,mnb = 1e18;
        for(int i=1;i<=k;i++){
            mna = min(mna,abs(x[a]-x[i]) + abs(y[a]-y[i]));
            mnb = min(mnb,abs(x[b]-x[i]) + abs(y[b]-y[i]));
        }
        ans = min(ans,mna+mnb);
        cout << ans << '\n';
    }
}


