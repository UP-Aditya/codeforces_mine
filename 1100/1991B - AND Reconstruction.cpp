int32_t main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int t;
    cin >> t;
    while(t--){
        int n;
        cin >> n;
        vector<int> v(n-1);
        for(int i=0;i<n-1;i++){
            cin >> v[i];
        }
        vector<int> b(n);
        b[0] = v[0];
        b[n-1] = v[n-2];
        for(int i=1;i<n-1;i++){
            b[i] = (v[i]|v[i-1]);
        }
        int f = 0;
        for(int i=0;i<n-1;i++){
            if((b[i]&b[i+1])!=v[i]){
                f = 1;
                break;
            }
        }
        if(f){
            cout << -1 << '\n';
        }
        else{
            for(auto &i : b){
                cout << i << " ";
            }
            cout << '\n';
        }


    }
}


